#!/usr/bin/env python3
"""Finite congruence-quotient probe for the algebraic presumption ladder.

Object: a fixed 4-element carrier S={0,1,2,3} carrying a bare binary
operation table (no laws imposed).  Four laws are imposed one at a time,
each as the congruence generated by the law's defining equations, closed
so the quotient operation is well-defined (standard congruence closure:
if a~b then x*a~x*b and a*x~b*x for all x, iterated to a fixpoint):

    magma --[+associativity]--> semigroup --[+identity]--> monoid
          --[+commutativity]--> commutative monoid --[+inverse]--> abelian group

Each arrow is a QUOTIENT map q: S_before -> S_after.  Per arrow:
(a) |S_before| and |S_after| are counted; structural entropy S=ln|S| drops
    by ln|S_before|-ln|S_after| (natural log, per spec).
(b) one_way is TRUE iff q is non-injective on this carrier -- witnessed by
    a concrete pair identified but distinct before, backed by a z3 (+cvc5)
    UNSAT-on-deterministic-recovery / SAT-once-erased pair.
(c) dual reading: presumption (laws assumed) goes up the chain while
    structural entropy goes down -- the two are coupled, not independent.
(d) a control chain (Z/4Z under addition, already associative, unital,
    commutative and cancellative from the start) runs through the SAME
    four congruence constructions; every arrow on it is COMPUTED (not
    hard-coded) to be a bijection, since none of the four laws add any
    new identification to an object that already satisfies them.

This is external fuel only: it measures finite syntactic/algebraic
quotients and does not establish a canonical, bridge, or axis-level
ratchet.  classification="tool_lego_fit_probe"; promotion_allowed=False.
"""
from __future__ import annotations

import itertools
import math
