def run_negative_tests():
    """
    Negative test 1: π_0(A(X)) missing Wall/K_0 components (UNSAT)
    Negative test 2: A(*) ≠ K(Z) (contradiction)
    Negative test 3: Splitting fails dimension count (UNSAT)
    """
    results = {}

    # NEGATIVE TEST 1: π_0(A(X)) with wrong rank (UNSAT)
    if TOOL_MANIFEST["cvc5"]["tried"]:
        try:
            solver = cvc5.Solver()
            solver.setLogic("QF_LIA")

            pi0_dim = solver.mkConst(solver.getIntegerSort(), "pi0_dim")
            wall_rank = solver.mkInteger(1)
            K0_rank = solver.mkInteger(1)
            expected = solver.mkTerm(cvc5.Kind.ADD, wall_rank, K0_rank)

            solver.assertFormula(solver.mkTerm(cvc5.Kind.EQUAL, expected, solver.mkInteger(2)))

            # NEGATIVE: Claim π_0(A) has rank 1 (should be UNSAT)
            solver.assertFormula(solver.mkTerm(cvc5.Kind.EQUAL, pi0_dim, solver.mkInteger(1)))

            sat = solver.checkSat()
            results["pi0_rank_mismatch_UNSAT"] = (
                sat.isUnsat(),
                {"theoretical": "UNSAT: π_0(A(X)) must have rank 2 for trivial π_1", "status": "UNSAT expected"}
            )
        except Exception as e:
            results["pi0_rank_mismatch_UNSAT"] = (False, {"error": str(e)})

    # NEGATIVE TEST 2: A(*) ≠ K(Z) in structure
    if TOOL_MANIFEST["sympy"]["tried"]:
        try:
            # A(*) must equal K(Z); claiming they differ contradicts definition
            pi0_A = 1
            pi0_K = 1
            mismatch = (pi0_A != pi0_K)

            results["A_point_neq_K_Z_fails"] = (
                not mismatch,  # Should be False (no mismatch)
                {"A(*)": pi0_A, "K(Z)": pi0_K, "must_be_equal": True}
            )
        except Exception as e:
            results["A_point_neq_K_Z_fails"] = (False, {"error": str(e)})

    # NEGATIVE TEST 3: Splitting dimension fails (UNSAT)
    if TOOL_MANIFEST["cvc5"]["tried"]:
        try:
            solver = cvc5.Solver()
            solver.setLogic("QF_LIA")

            rank_A = solver.mkInteger(2)
            rank_stable = solver.mkInteger(1)
            rank_Wh = solver.mkConst(solver.getIntegerSort(), "rank_Wh")

            # Correct splitting: rank_A = rank_stable + rank_Wh
            expected = solver.mkTerm(cvc5.Kind.ADD, rank_stable, rank_Wh)
            solver.assertFormula(solver.mkTerm(cvc5.Kind.EQUAL, rank_A, expected))

            # NEGATIVE: Claim rank_Wh makes the sum wrong (e.g., rank_A = 3) → UNSAT
            solver.assertFormula(solver.mkTerm(cvc5.Kind.EQUAL, rank_A, solver.mkInteger(3)))

            sat = solver.checkSat()
            results["splitting_dimension_violated_UNSAT"] = (
                sat.isUnsat(),
                {"theoretical": "UNSAT: Splitting dimension count must be consistent", "status": "UNSAT expected"}
            )
        except Exception as e:
            results["splitting_dimension_violated_UNSAT"] = (False, {"error": str(e)})

    return results


