def run_positive_tests():
    results = {}

    # Test 1: K_0 rank constraint via cvc5
    try:
        import cvc5
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        # K_0(R) has rank at most equal to number of indecomposable projectives
        num_indecomp = solver.mkConst(solver.getIntegerSort(), "num_indecomp")
        k0_rank = solver.mkConst(solver.getIntegerSort(), "k0_rank")

        # Constraint: k0_rank <= num_indecomp
        solver.assertFormula(solver.mkTerm(cvc5.Kind.LEQ, k0_rank, num_indecomp))

        result = solver.checkSat()
        results["test_k0_rank_constraint_sat"] = str(result.isSat())

        # Now test UNSAT: claim k0_rank > num_indecomp (should be impossible)
        solver2 = cvc5.Solver()
        solver2.setLogic("QF_LIA")
        num_indecomp2 = solver2.mkConst(solver2.getIntegerSort(), "num_indecomp")
        k0_rank2 = solver2.mkConst(solver2.getIntegerSort(), "k0_rank")
        solver2.assertFormula(solver2.mkTerm(cvc5.Kind.GT, k0_rank2, num_indecomp2))
        solver2.assertFormula(solver2.mkTerm(cvc5.Kind.EQ, k0_rank2, solver2.mkInteger(10)))
        solver2.assertFormula(solver2.mkTerm(cvc5.Kind.EQ, num_indecomp2, solver2.mkInteger(5)))

        result2 = solver2.checkSat()
        results["test_k0_rank_violates_unsat"] = str(result2.isSat())

    except Exception as e:
        results["test_k0_rank_error"] = str(e)

    # Test 2: K_1(F_p) multiplicative structure via sympy
    try:
        import sympy as sp
        p = 7  # F_7
        # K_1(F_7) should be isomorphic to F_7* which has order p-1 = 6
        k1_order = p - 1
        results["test_k1_fp_order"] = k1_order

        # Verify: all elements of F_7* have order dividing 6
        orders = []
        for x in range(1, p):
            for d in range(1, k1_order + 1):
                if (x ** d) % p == 1:
                    orders.append(d)
                    break
        results["test_k1_fp_element_orders"] = sorted(set(orders))

    except Exception as e:
        results["test_k1_fp_error"] = str(e)

    # Test 3: Adams operations ψ^k on K_{2n-1}
    try:
        import sympy as sp
        # For finite field F_q, Adams operation ψ^k acts on K_{2n-1}(F_q) by multiplication by k^n
        q = 3
        n = 2
        k = 2

        # K_3(F_3) = Z/(3^2 - 1) = Z/8
        k_order = q**n - 1

        # Action of ψ^k should multiply by k^n
        psi_eigenvalue = k**n % k_order
        results["test_adams_op_k23_eigenvalue"] = psi_eigenvalue
        results["test_adams_op_k23_order"] = k_order

    except Exception as e:
        results["test_adams_op_error"] = str(e)

    return results


