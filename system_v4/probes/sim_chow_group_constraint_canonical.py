def run_positive_tests():
    """
    Verify that cvc5 SAT confirms zero-cycles with integer degrees.
    """
    results = {}

    if not TOOL_MANIFEST["cvc5"]["tried"]:
        return results

    import cvc5

    # Test 1: Zero-cycle with degree 1 on P^2 (single rational point)
    try:
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")
        solver.setOption("produce-models", "true")

        int_sort = solver.getIntegerSort()

        # A zero-cycle on P^2 is a formal sum of points: Z = sum_i m_i * p_i
        # Degree is: deg(Z) = sum_i m_i
        m1 = solver.mkConst(int_sort, "m1")  # multiplicity of first point
        m2 = solver.mkConst(int_sort, "m2")  # multiplicity of second point

        # Degree: deg(Z) = m1 + m2
        degree = solver.mkTerm(cvc5.Kind.ADD, m1, m2)

        # Constraint: degree is 1 (single rational point)
        degree_constraint = solver.mkTerm(cvc5.Kind.EQUAL, degree, solver.mkInteger(1))

        # Additional: both multiplicities are non-negative (valid for positive cycle)
        m1_nonneg = solver.mkTerm(cvc5.Kind.GEQ, m1, solver.mkInteger(0))
        m2_nonneg = solver.mkTerm(cvc5.Kind.GEQ, m2, solver.mkInteger(0))

        solver.assertFormula(degree_constraint)
        solver.assertFormula(m1_nonneg)
        solver.assertFormula(m2_nonneg)

        is_sat = solver.checkSat().isSat()
        results["test_positive_degree_one_cycle"] = {
            "description": "cvc5 SAT: zero-cycle with degree 1 on P^2",
            "sat": is_sat,
            "expected": True,
        }

        if is_sat:
            model = solver.getValue([m1, m2, degree])
            results["test_positive_degree_one_cycle"]["model"] = str(model)

        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["test_positive_degree_one_cycle"] = {"error": str(e)}

    # Test 2: Zero-cycle with degree 4 (sum of 4 rational points)
    try:
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")
        solver.setOption("produce-models", "true")

        int_sort = solver.getIntegerSort()

        # Zero-cycle: Z = p1 + p2 + p3 + p4 (four distinct points)
        m1 = solver.mkConst(int_sort, "m1")
        m2 = solver.mkConst(int_sort, "m2")
        m3 = solver.mkConst(int_sort, "m3")
        m4 = solver.mkConst(int_sort, "m4")

        # Degree: deg(Z) = m1 + m2 + m3 + m4
        degree = solver.mkTerm(cvc5.Kind.ADD, m1, m2, m3, m4)

        # Constraint: degree is 4
        degree_constraint = solver.mkTerm(cvc5.Kind.EQUAL, degree, solver.mkInteger(4))

        # All multiplicities are 1 (simple points)
        m1_one = solver.mkTerm(cvc5.Kind.EQUAL, m1, solver.mkInteger(1))
        m2_one = solver.mkTerm(cvc5.Kind.EQUAL, m2, solver.mkInteger(1))
        m3_one = solver.mkTerm(cvc5.Kind.EQUAL, m3, solver.mkInteger(1))
        m4_one = solver.mkTerm(cvc5.Kind.EQUAL, m4, solver.mkInteger(1))

        solver.assertFormula(degree_constraint)
        solver.assertFormula(m1_one)
        solver.assertFormula(m2_one)
        solver.assertFormula(m3_one)
        solver.assertFormula(m4_one)

        is_sat = solver.checkSat().isSat()
        results["test_positive_degree_four_cycle"] = {
            "description": "cvc5 SAT: zero-cycle with degree 4 (four simple points)",
            "sat": is_sat,
            "expected": True,
        }

        if is_sat:
            model = solver.getValue([m1, m2, m3, m4, degree])
            results["test_positive_degree_four_cycle"]["model"] = str(model)

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_positive_degree_four_cycle"] = {"error": str(e)}

    # Test 3: Zero-cycle with multiplicity (degree 3)
    try:
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")
        solver.setOption("produce-models", "true")

        int_sort = solver.getIntegerSort()

        # Zero-cycle: Z = 3*p (triple point)
        m = solver.mkConst(int_sort, "multiplicity")
        degree = m

        # Constraint: degree is 3
        degree_constraint = solver.mkTerm(cvc5.Kind.EQUAL, degree, solver.mkInteger(3))

        # Multiplicity must be positive
        m_positive = solver.mkTerm(cvc5.Kind.GT, m, solver.mkInteger(0))

        solver.assertFormula(degree_constraint)
        solver.assertFormula(m_positive)

        is_sat = solver.checkSat().isSat()
        results["test_positive_multiplicity_cycle"] = {
            "description": "cvc5 SAT: zero-cycle with multiplicity (degree 3)",
            "sat": is_sat,
            "expected": True,
        }

        if is_sat:
            model = solver.getValue([m, degree])
            results["test_positive_multiplicity_cycle"]["model"] = str(model)

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_positive_multiplicity_cycle"] = {"error": str(e)}

    return results


