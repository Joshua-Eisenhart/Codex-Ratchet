def run_negative_tests():
    """
    Verify that cvc5 UNSAT rules out non-integer degrees.
    """
    results = {}

    if not TOOL_MANIFEST["cvc5"]["tried"]:
        return results

    import cvc5

    # Test 1: UNSAT - fractional degree on integer variety
    try:
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()

        # Axiom: degree of any cycle is an integer
        # (implicit in QF_LIA: all expressions are integer-valued)

        # For proper algebraic variety, degree must be integer
        # We encode: degree = 1 AND degree = 3/2 is impossible
        # In QF_LIA: we can't represent 3/2 directly, but we can say
        # 2*degree = 3 AND degree is integer → UNSAT

        degree = solver.mkConst(int_sort, "degree")

        # 2*degree = 3 (would require degree = 1.5, non-integer)
        two_times_degree = solver.mkTerm(cvc5.Kind.MULT, solver.mkInteger(2), degree)
        fractional_degree_claim = solver.mkTerm(cvc5.Kind.EQUAL, two_times_degree, solver.mkInteger(3))

        solver.assertFormula(fractional_degree_claim)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_fractional_degree"] = {
            "description": "cvc5 UNSAT: 2*degree = 3 in QF_LIA (no integer solution)",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["test_negative_fractional_degree"] = {"error": str(e)}

    # Test 2: UNSAT - contradictory degree constraints
    try:
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()

        m1 = solver.mkConst(int_sort, "m1")
        m2 = solver.mkConst(int_sort, "m2")

        degree = solver.mkTerm(cvc5.Kind.ADD, m1, m2)

        # Axiom: degree = 1
        axiom_degree_one = solver.mkTerm(cvc5.Kind.EQUAL, degree, solver.mkInteger(1))

        # Violation: degree = 2
        violation_degree_two = solver.mkTerm(cvc5.Kind.EQUAL, degree, solver.mkInteger(2))

        solver.assertFormula(axiom_degree_one)
        solver.assertFormula(violation_degree_two)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_contradictory_degree"] = {
            "description": "cvc5 UNSAT: degree = 1 AND degree = 2 is impossible",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_negative_contradictory_degree"] = {"error": str(e)}

    # Test 3: UNSAT - negative degree on positive cycle
    try:
        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()

        m1 = solver.mkConst(int_sort, "m1")
        m2 = solver.mkConst(int_sort, "m2")

        degree = solver.mkTerm(cvc5.Kind.ADD, m1, m2)

        # Axiom: multiplicities are non-negative (positive cycle)
        m1_nonneg = solver.mkTerm(cvc5.Kind.GEQ, m1, solver.mkInteger(0))
        m2_nonneg = solver.mkTerm(cvc5.Kind.GEQ, m2, solver.mkInteger(0))

        # Axiom: degree is non-negative
        degree_nonneg = solver.mkTerm(cvc5.Kind.GEQ, degree, solver.mkInteger(0))

        # Violation: degree < 0
        violation = solver.mkTerm(cvc5.Kind.LT, degree, solver.mkInteger(0))

        solver.assertFormula(m1_nonneg)
        solver.assertFormula(m2_nonneg)
        solver.assertFormula(degree_nonneg)
        solver.assertFormula(violation)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_negative_degree"] = {
            "description": "cvc5 UNSAT: non-negative cycle cannot have negative degree",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_negative_negative_degree"] = {"error": str(e)}

    return results


