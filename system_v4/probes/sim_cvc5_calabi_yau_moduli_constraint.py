def run_negative_tests():
    """
    Verify cvc5 UNSAT rules out CY with zero Kähler moduli.
    """
    results = {}

    # Test 1: UNSAT - h^{1,1} = 0 with "compact CY" claim
    try:
        import cvc5

        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()
        h11 = solver.mkConst(int_sort, "h11")
        is_compact_cy = solver.mkConst(cvc5.Kind.CONST_BOOLEAN, "is_compact_cy")

        # Axiom: if compact CY, then h^{1,1} ≥ 1 (must have Kähler moduli)
        # Equivalently: h^{1,1} = 0 implies not compact CY
        cy_implies_kahler = solver.mkTerm(cvc5.Kind.IMPLIES,
                                          is_compact_cy,
                                          solver.mkTerm(cvc5.Kind.GEQ, h11, solver.mkInteger(1)))

        # Violation: claim compact CY but h^{1,1} = 0
        claim_cy = is_compact_cy
        no_kahler = solver.mkTerm(cvc5.Kind.EQUAL, h11, solver.mkInteger(0))

        solver.assertFormula(cy_implies_kahler)
        solver.assertFormula(claim_cy)
        solver.assertFormula(no_kahler)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_zero_kahler_moduli"] = {
            "description": "cvc5 UNSAT: h^{1,1} = 0 with 'compact CY' claim (Kähler moduli required for CY)",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["test_negative_zero_kahler_moduli"] = {"error": str(e)}

    # Test 2: UNSAT - Hodge constraint violated: h^{1,1} + h^{2,1} ≠ χ/2 + 1
    try:
        import cvc5

        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()
        h11 = solver.mkConst(int_sort, "h11")
        h21 = solver.mkConst(int_sort, "h21")
        chi = solver.mkConst(int_sort, "euler_characteristic")

        # Hodge constraint: h^{1,1} + h^{2,1} = χ/2 + 1
        hodge_constraint = solver.mkTerm(cvc5.Kind.EQUAL,
                                        solver.mkTerm(cvc5.Kind.PLUS, h11, h21),
                                        solver.mkTerm(cvc5.Kind.PLUS,
                                                     solver.mkInteger(1),
                                                     solver.mkTerm(cvc5.Kind.INTS_DIVISION, chi, solver.mkInteger(2))))

        # Violation: claim CY3 but violate Hodge
        h11_val = solver.mkTerm(cvc5.Kind.EQUAL, h11, solver.mkInteger(2))
        h21_val = solver.mkTerm(cvc5.Kind.EQUAL, h21, solver.mkInteger(272))
        chi_val = solver.mkTerm(cvc5.Kind.EQUAL, chi, solver.mkInteger(0))  # Wrong: should be 542

        solver.assertFormula(hodge_constraint)
        solver.assertFormula(h11_val)
        solver.assertFormula(h21_val)
        solver.assertFormula(chi_val)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_hodge_violated"] = {
            "description": "cvc5 UNSAT: h^{1,1}=2, h^{2,1}=272, χ=0 (violates h^{1,1}+h^{2,1}=χ/2+1 constraint)",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_negative_hodge_violated"] = {"error": str(e)}

    # Test 3: UNSAT - h^{1,1} and h^{2,1} cannot both be negative
    try:
        import cvc5

        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()
        h11 = solver.mkConst(int_sort, "h11")
        h21 = solver.mkConst(int_sort, "h21")

        # Axiom: Hodge numbers are non-negative (dimension of cohomology spaces)
        h11_nonneg = solver.mkTerm(cvc5.Kind.GEQ, h11, solver.mkInteger(0))
        h21_nonneg = solver.mkTerm(cvc5.Kind.GEQ, h21, solver.mkInteger(0))

        # Violation: attempt negative Hodge number
        h11_val = solver.mkTerm(cvc5.Kind.EQUAL, h11, solver.mkInteger(-1))

        solver.assertFormula(h11_nonneg)
        solver.assertFormula(h21_nonneg)
        solver.assertFormula(h11_val)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_negative_hodge"] = {
            "description": "cvc5 UNSAT: h^{1,1} = -1 (Hodge numbers are non-negative by definition)",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_negative_negative_hodge"] = {"error": str(e)}

    return results


