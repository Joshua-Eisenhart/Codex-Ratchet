def run_negative_tests():
    """
    Verify cvc5 UNSAT rules out impossible cobordism configurations.
    """
    results = {}

    # Test 1: UNSAT - boundary manifold with nontrivial cobordism class
    try:
        import cvc5

        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()
        has_boundary = solver.mkConst(int_sort, "has_boundary")
        cobordism_class = solver.mkConst(int_sort, "cobordism_class")

        # Axiom: ∂M≠∅ ⟹ [M]=0
        has_boundary_val = solver.mkTerm(cvc5.Kind.EQUAL, has_boundary, solver.mkInteger(1))
        # Implication: if has_boundary=1, then cobordism_class=0
        cob_zero = solver.mkTerm(cvc5.Kind.EQUAL, cobordism_class, solver.mkInteger(0))
        # Violation: cobordism_class ≠ 0
        cob_nonzero = solver.mkTerm(cvc5.Kind.EQUAL, cobordism_class, solver.mkInteger(1))

        solver.assertFormula(has_boundary_val)
        solver.assertFormula(cob_zero)
        solver.assertFormula(cob_nonzero)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_boundary_nontrivial"] = {
            "description": "cvc5 UNSAT: Boundary manifold (∂M≠∅) with nontrivial class [M]=1 violates cobordism axiom",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["test_negative_boundary_nontrivial"] = {"error": str(e)}

    # Test 2: UNSAT - closed manifold claim on manifold with boundary
    try:
        import cvc5

        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()
        has_boundary = solver.mkConst(int_sort, "has_boundary")
        is_closed = solver.mkConst(int_sort, "is_closed")

        # Axiom: has_boundary XOR is_closed (manifold is either closed or has boundary)
        has_boundary_val = solver.mkTerm(cvc5.Kind.EQUAL, has_boundary, solver.mkInteger(1))
        # Violation: claim is_closed=1 when has_boundary=1
        is_closed_val = solver.mkTerm(cvc5.Kind.EQUAL, is_closed, solver.mkInteger(1))
        # Both cannot be true
        mutual_exclusive = solver.mkTerm(cvc5.Kind.NOT,
                                        solver.mkTerm(cvc5.Kind.AND,
                                                     has_boundary_val, is_closed_val))

        solver.assertFormula(mutual_exclusive)
        solver.assertFormula(has_boundary_val)
        solver.assertFormula(is_closed_val)

        is_unsat = solver.checkSat().isUnsat()
        results["test_negative_closed_boundary_contradiction"] = {
            "description": "cvc5 UNSAT: Manifold cannot be both closed (∂M=∅) and have boundary (∂M≠∅)",
            "unsat": is_unsat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_negative_closed_boundary_contradiction"] = {"error": str(e)}

    # Test 3: UNSAT - boundary cobordism violation
    try:
        import cvc5

        solver = cvc5.Solver()
        solver.setLogic("QF_LIA")

        int_sort = solver.getIntegerSort()
        bd_m = solver.mkConst(int_sort, "boundary_M")
        bd_n = solver.mkConst(int_sort, "boundary_N")
        cob_mn_difference = solver.mkConst(int_sort, "cob_difference")

        # If M~N (M and N are cobordant), and M has boundary, then N has boundary
        # Axiom: if both have boundary, cobordism difference is zero
        bd_m_val = solver.mkTerm(cvc5.Kind.EQUAL, bd_m, solver.mkInteger(1))
        bd_n_val = solver.mkTerm(cvc5.Kind.EQUAL, bd_n, solver.mkInteger(1))
        cob_diff_zero = solver.mkTerm(cvc5.Kind.EQUAL, cob_mn_difference, solver.mkInteger(0))

        solver.assertFormula(bd_m_val)
        solver.assertFormula(bd_n_val)
        solver.assertFormula(cob_diff_zero)

        is_sat = solver.checkSat().isSat()
        results["test_negative_cobordant_boundary_manifolds"] = {
            "description": "cvc5 SAT: Cobordant boundary manifolds both satisfy zero cobordism condition",
            "sat": is_sat,
            "expected": True,
        }

        TOOL_MANIFEST["cvc5"]["used"] = True
    except Exception as e:
        results["test_negative_cobordant_boundary_manifolds"] = {"error": str(e)}

    return results


