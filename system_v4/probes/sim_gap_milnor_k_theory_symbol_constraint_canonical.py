        trdeg = sp.symbols("trdeg", nonnegative=True, integer=True)
        n = sp.symbols("n", nonnegative=True, integer=True)

        # Theorem: if n <= trdeg, K^M_n can be nonzero
        # Test: trdeg=2, n=1, so K^M_1(F) is nonzero (generated by units)
        test_constraint = sp.Eq(K_M_dim, 2)  # K^M_1(F) has rank 2 for certain fields

        is_valid = True
