def run_negative_tests():
    """Test violations of wrapped Fukaya category properties (should be UNSAT)."""
    results = {}

    if not TOOL_MANIFEST["cvc5"]["tried"]:
        return results

    import cvc5

    # Negative Test 1: Wrapping index is negative (UNSAT)
    solver1 = cvc5.Solver()
    solver1.setLogic("QF_LIA")

    wrapping_index = solver1.mkInteger(-1)  # invalid: negative

    # Assert: wrapping index ≥ 0
    solver1.assertFormula(solver1.mkTerm(cvc5.Kind.GEQ, wrapping_index, solver1.mkInteger(0)))

    is_unsat_1 = solver1.checkSat().isUnsat()
    results["neg_test_1_negative_wrapping_index"] = {
        "wrapping_index": -1,
        "unsatisfiable": is_unsat_1,
        "expected": True,
        "pass": is_unsat_1 == True,
    }

    # Negative Test 2: Non-composable morphisms (UNSAT)
    solver2 = cvc5.Solver()
    solver2.setLogic("QF_LIA")

    # Morphism from L_0 to L_1 exists, but morphism from L_2 to L_1 (wrong direction)
    morphism_0_to_1 = solver2.mkInteger(1)
    morphism_2_to_1 = solver2.mkInteger(1)

    # Composition 0->1->2 should NOT exist
    composition = solver2.mkInteger(0)

    # Assert: if composition exists, it must be 1
    solver2.assertFormula(solver2.mkTerm(cvc5.Kind.EQUAL, composition, solver2.mkInteger(0)))
    solver2.assertFormula(
        solver2.mkTerm(cvc5.Kind.EQUAL, morphism_0_to_1, solver2.mkInteger(1))
    )
    # But claim composition must be 1 if morphisms exist
    solver2.assertFormula(
        solver2.mkTerm(cvc5.Kind.GEQ, composition, morphism_0_to_1)
    )

    is_unsat_2 = solver2.checkSat().isUnsat()
    results["neg_test_2_non_composable_morphisms"] = {
        "morphism_1": 1,
        "composition": 0,
        "unsatisfiable": is_unsat_2,
        "expected": True,
        "pass": is_unsat_2 == True,
    }

    # Negative Test 3: Non-generating vanishing cycles (UNSAT)
    solver3 = cvc5.Solver()
    solver3.setLogic("QF_LIA")

    num_vanishing = solver3.mkInteger(0)  # no vanishing cycles
    is_generating = solver3.mkInteger(1)  # but claim they generate

    # Assert: vanishing cycles must generate
    solver3.assertFormula(solver3.mkTerm(cvc5.Kind.EQUAL, is_generating, solver3.mkInteger(1)))
    solver3.assertFormula(solver3.mkTerm(cvc5.Kind.EQUAL, num_vanishing, solver3.mkInteger(0)))
    # Contradiction: can't generate if there are none
    solver3.assertFormula(solver3.mkTerm(cvc5.Kind.GEQ, num_vanishing, solver3.mkInteger(1)))

    is_unsat_3 = solver3.checkSat().isUnsat()
    results["neg_test_3_non_generating_vanishing_cycles"] = {
        "num_vanishing": 0,
        "is_generating": 1,
        "unsatisfiable": is_unsat_3,
        "expected": True,
        "pass": is_unsat_3 == True,
    }

    return results


