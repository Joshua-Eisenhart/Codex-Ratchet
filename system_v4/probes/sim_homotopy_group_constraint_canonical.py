def run_negative_tests():
    """
    Negative tests: Non-integer winding falsifies π_n(S^n) membership
    """
    results = {
        "non_integer_winding_unsat": None,
        "fractional_degree_unsat": None,
        "mixed_integer_noninteger_unsat": None,
    }

    if not Z3_AVAILABLE:
        return results

    # Test 1: Non-integer winding contradicts group structure
    solver = Solver()
    winding = Real("winding")
    is_integer = Bool("is_integer")

    solver.add(winding == 1.5)  # Non-integer
    solver.add(ForAll([is_integer], Implies(is_integer, winding == Int("w"))))  # Claim it's in π_n(S^n)
    # This creates contradiction: 1.5 cannot equal any integer
    solver.add(Or([winding == i for i in range(-10, 11)]))  # Must be some integer

    if solver.check() == unsat:
        results["non_integer_winding_unsat"] = {
            "status": "unsat",
            "interpretation": "Winding 1.5 contradicts π_n(S^n) = ℤ; homotopy group admits only integer degrees; fractional winding is structurally forbidden",
        }

    # Test 2: Fractional degree of map
    solver2 = Solver()
    degree_frac = Real("degree_frac")
    n_val = Int("n_val")

    solver2.add(degree_frac == 2.7)
    solver2.add(n_val == 2)
    solver2.add(degree_frac > 0)
    # Try to force integer constraint
    solver2.add(degree_frac == Int("d_int"))

    if solver2.check() == unsat:
        results["fractional_degree_unsat"] = {
            "status": "unsat",
            "interpretation": "Degree 2.7 for map S^2 → S^2 contradicts π_2(S^2) = ℤ; all homotopy classes are integer-indexed",
        }

    # Test 3: Composition of integer winding with non-integer leads to UNSAT
    solver3 = Solver()
    w_int = Int("w_int")
    w_frac = Real("w_frac")
    result = Real("result")

    solver3.add(w_int == 2)
    solver3.add(w_frac == 1.5)
    solver3.add(result == w_int + w_frac)
    solver3.add(result == Int("r_int"))  # Try to claim result is integer

    if solver3.check() == unsat:
        results["mixed_integer_noninteger_unsat"] = {
            "status": "unsat",
            "interpretation": "Composition of integer 2 + non-integer 1.5 = 3.5 cannot be integer; mixing integer and non-integer homotopy classes is forbidden",
        }

    return results


