def run_negative_tests():
    """
    Negative tests verify that invalid/contradictory states are UNSAT in cvc5.
    """
    results = {}

    # Test 1: UNSAT — rank(X) > 0 AND char_ideal = unit (by Main Conjecture)
    if cvc5_available:
        try:
            TOOL_MANIFEST["cvc5"]["used"] = True
            solver = cvc5.Solver()
            solver.setLogic("QF_NIA")

            rank = solver.mkConst(solver.getIntegerSort(), "rank")
            char_is_unit = solver.mkConst(solver.getBooleanSort(), "char_is_unit")
            char_nonunit = solver.mkConst(solver.getBooleanSort(), "char_nonunit")

            # Main Conjecture constraint: if char_ideal is the ideal (f_p), then it's nonunit when X is nonzero
            # Equivalently: rank > 0 implies char is not a unit
            solver.assertFormula(
                solver.mkTerm(cvc5.Kind.IMPLIES,
                    solver.mkTerm(cvc5.Kind.GT, rank, solver.mkInteger(0)),
                    char_nonunit
                )
            )

            # Claim: rank(X) > 0 AND char_ideal = unit AND enforce that char_nonunit = NOT char_is_unit
            solver.assertFormula(solver.mkTerm(cvc5.Kind.GT, rank, solver.mkInteger(0)))
            solver.assertFormula(char_is_unit)
            solver.assertFormula(solver.mkTerm(cvc5.Kind.EQUAL, char_nonunit, solver.mkTerm(cvc5.Kind.NOT, char_is_unit)))

            sat = solver.checkSat().isSat()
            results["test_nonzero_rank_unit_char_unsat"] = {
                "description": "rank(X) > 0 AND char_ideal=unit is UNSAT (Main Conjecture forbids)",
                "satisfiable": sat,
                "passed": not sat  # Should be UNSAT
            }
        except Exception as e:
            results["test_nonzero_rank_unit_char_unsat"] = {"passed": False, "error": str(e)}

    # Test 2: UNSAT — negative μ-invariant
    if cvc5_available:
        try:
            solver = cvc5.Solver()
            solver.setLogic("QF_NIA")

            mu = solver.mkConst(solver.getIntegerSort(), "mu")

            # Iwasawa theorem: μ(Λ-module X) ≥ 0 always (non-negativity constraint)
            solver.assertFormula(solver.mkTerm(cvc5.Kind.GEQ, mu, solver.mkInteger(0)))

            # Claim: μ < 0 (contradicts theorem)
            solver.assertFormula(solver.mkTerm(cvc5.Kind.LT, mu, solver.mkInteger(0)))

            sat = solver.checkSat().isSat()
            results["test_negative_mu_unsat"] = {
                "description": "μ-invariant < 0 is UNSAT (non-negativity by theorem)",
                "satisfiable": sat,
                "passed": not sat  # Should be UNSAT
            }
        except Exception as e:
            results["test_negative_mu_unsat"] = {"passed": False, "error": str(e)}

    # Test 3: UNSAT — characteristic ideal equals both nonunit and unit
    if cvc5_available:
        try:
            solver = cvc5.Solver()
            solver.setLogic("QF_NRA")

            is_unit_a = solver.mkConst(solver.getBooleanSort(), "is_unit_a")
            is_unit_b = solver.mkConst(solver.getBooleanSort(), "is_unit_b")

            # Contradictory claim
            solver.assertFormula(is_unit_a)
            solver.assertFormula(solver.mkTerm(cvc5.Kind.NOT, is_unit_b))
            solver.assertFormula(solver.mkTerm(cvc5.Kind.EQUAL, is_unit_a, is_unit_b))

            sat = solver.checkSat().isSat()
            results["test_char_contradiction_unsat"] = {
                "description": "characteristic ideal cannot be both unit and nonunit",
                "satisfiable": sat,
                "passed": not sat  # Should be UNSAT
            }
        except Exception as e:
            results["test_char_contradiction_unsat"] = {"passed": False, "error": str(e)}

    return results


