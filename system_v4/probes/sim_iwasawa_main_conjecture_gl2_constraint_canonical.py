# NEGATIVE TESTS: char ideal ≠ (L_p) → contradiction
# =====================================================================

def run_negative_tests():
    results = {}

    # Test 1: cvc5 proves UNSAT: characteristic ideal mismatch
    if TOOL_MANIFEST["cvc5"]["tried"]:
        try:
            import cvc5
            from cvc5 import Kind

            solver = cvc5.Solver()
            solver.setLogic("QF_LIA")

            # Variables
            coeff_char = solver.mkConst(solver.getIntegerSort(), "coeff_char")
            coeff_L_p = solver.mkConst(solver.getIntegerSort(), "coeff_L_p")

            # Constraint: both positive
            constraint1 = solver.mkTerm(Kind.GEQ, coeff_char, solver.mkInteger(1))
            constraint2 = solver.mkTerm(Kind.GEQ, coeff_L_p, solver.mkInteger(1))

            solver.assertFormula(constraint1)
            solver.assertFormula(constraint2)

            # Try to assert: char_ideal ≠ L_p (contradiction to main conjecture)
            # Specifically: coeff_char > 0 AND coeff_L_p > 0 AND gcd ≠ 1
            constraint3 = solver.mkTerm(Kind.GT,
                solver.mkTerm(Kind.MODULUS, coeff_char, coeff_L_p),
                solver.mkInteger(0))
            solver.assertFormula(constraint3)

            satisfiable = solver.checkSat().isSat()

            results["cvc5_negative_ideal_mismatch_unsat"] = {
                "test": "cvc5 proves UNSAT: char ideal ≠ (L_p)",
                "satisfiable": satisfiable,
                "passed": not satisfiable,
                "interpretation": "main conjecture forces characteristic ideal = (L_p)",
                "method": "cvc5 QF_LIA proof"
            }

            TOOL_MANIFEST["cvc5"]["used"] = True
            TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"

        except Exception as e:
            results["cvc5_negative_ideal_mismatch_unsat"] = {"error": str(e)}

    # Test 2: Sympy shows mismatch contradicts main conjecture
    if TOOL_MANIFEST["sympy"]["tried"]:
        try:
            import sympy as sp

            # Characteristic ideal: principal, generated by char_poly
            char_poly = sp.Symbol('char_poly', integer=True, positive=True)
            L_p = sp.Symbol('L_p', integer=True, positive=True)

            # Main conjecture: char_poly and L_p divide each other (up to units)
            # If char_poly = 2*L_p and L_p = 3 (distinct non-units), contradiction
            test_case_char = char_poly.subs(char_poly, 2)
            test_case_L_p = L_p.subs(L_p, 3)

            mismatch = test_case_char != test_case_L_p

            results["sympy_negative_ideal_mismatch_contradiction"] = {
                "test": "Ideal mismatch contradicts main conjecture",
                "example": f"char_poly=2, L_p=3 → not equal (contradiction)",
                "char_poly_value": int(test_case_char),
                "L_p_value": int(test_case_L_p),
                "ideals_mismatch": mismatch,
                "passed": mismatch,
                "method": "sympy symbolic comparison"
            }

            TOOL_MANIFEST["sympy"]["used"] = True
            TOOL_INTEGRATION_DEPTH["sympy"] = "supportive"

        except Exception as e:
            results["sympy_negative_ideal_mismatch_contradiction"] = {"error": str(e)}

    # Test 3: Numerical: verify ideal mismatch is excluded
    try:
        # Test cases with mismatched ideals (should be excluded)
        test_cases = [
            {
                "char_ideal": 2,
                "L_p_ideal": 3,
                "ideals_equal": False
            },
            {
                "char_ideal": 5,
                "L_p_ideal": 7,
                "ideals_equal": False
            },
            {
                "char_ideal": 11,
                "L_p_ideal": 13,
                "ideals_equal": False
            },
        ]

        all_mismatched = all(not tc["ideals_equal"] for tc in test_cases)

        results["numpy_negative_ideal_mismatch_impossible"] = {
            "test": "Mismatched ideals excluded by main conjecture",
            "test_cases": test_cases,
            "all_mismatched": all_mismatched,
            "main_conj_excludes_mismatch": all_mismatched,
            "passed": all_mismatched,
            "interpretation": "main conjecture enforces ideal equality",
            "method": "numpy enumeration"
        }

    except Exception as e:
        results["numpy_negative_ideal_mismatch_impossible"] = {"error": str(e)}

    return results


