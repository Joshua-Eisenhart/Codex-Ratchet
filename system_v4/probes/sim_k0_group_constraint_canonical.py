"""
K_0 Group Canonical Sim

K_0 is the Grothendieck group of projective modules. For a commutative ring R,
K_0(R) is generated by isomorphism classes [P] of finitely generated projective
modules, with the relation [P] = [Q] + [P/Q] when Q is a direct summand of P.

For a PID (principal ideal domain) like Z, every finitely generated projective
module is free. Thus K_0(Z) ≅ Z, generated by the rank of free modules.

This sim uses cvc5 to verify:
- The isomorphism K_0(Z) ≅ Z (via rank)
- UNSAT when projective modules over Z claim non-trivial class but are free
- Sympy verifies the rank computation for specific free modules
"""

