# NEGATIVE TESTS: Inconsistent projective claims over Z
# =====================================================================

def run_negative_tests():
    results = {}

    # Test 1: UNSAT when claiming module is projective but not free (contradiction for Z)
    if TOOL_MANIFEST["cvc5"]["tried"]:
        try:
            import cvc5

            TOOL_MANIFEST["cvc5"]["used"] = True

            tm = cvc5.TermManager()
            solver = cvc5.Solver(tm)

            # Over a PID like Z, every finitely generated projective is free
            is_projective = tm.mkConst(tm.getBooleanSort(), "is_projective")
            is_free = tm.mkConst(tm.getBooleanSort(), "is_free")

            # Constraint: if module over Z and projective, then it's free
            # So: is_projective ∧ ¬is_free is UNSAT for Z-modules
            solver.assertFormula(tm.mkTerm(cvc5.Kind.And,
                                            is_projective,
                                            tm.mkTerm(cvc5.Kind.Not, is_free)))

            # For Z (PID), projective implies free
            solver.assertFormula(tm.mkTerm(cvc5.Kind.Implies, is_projective, is_free))

            is_sat = solver.checkSat().isSat()

            results["test_1_projective_not_free_unsat"] = {
                "description": "Over Z, projective ∧ ¬free is UNSAT",
                "cvc5_sat": is_sat,
                "expected_sat": False,
                "correct": not is_sat,
            }
        except Exception as e:
            results["test_1_projective_not_free_unsat"] = {"error": str(e)}

    # Test 2: UNSAT when claiming non-trivial torsion in K_0(Z)
    if TOOL_MANIFEST["cvc5"]["tried"]:
        try:
            import cvc5

            tm = cvc5.TermManager()
            solver = cvc5.Solver(tm)

            # K_0(Z) ≅ Z has no torsion
            # So: [P] has torsion order n > 1 is UNSAT
            torsion_order = tm.mkConst(tm.getIntegerSort(), "torsion_order")

            # Constraint: if torsion order > 1 in K_0(Z), this contradicts K_0(Z) ≅ Z
            solver.assertFormula(tm.mkTerm(cvc5.Kind.Gt, torsion_order, tm.mkInteger(1)))

            # K_0(Z) is torsion-free (isomorphic to Z)
            solver.assertFormula(tm.mkTerm(cvc5.Kind.Equal, torsion_order, tm.mkInteger(1)))

            is_sat = solver.checkSat().isSat()

            results["test_2_torsion_unsat"] = {
                "description": "Non-trivial torsion in K_0(Z) is UNSAT (Z is torsion-free)",
                "cvc5_sat": is_sat,
                "expected_sat": False,
                "correct": not is_sat,
            }
        except Exception as e:
            results["test_2_torsion_unsat"] = {"error": str(e)}

    # Test 3: UNSAT when claiming negative rank
    if TOOL_MANIFEST["cvc5"]["tried"]:
        try:
            import cvc5

            tm = cvc5.TermManager()
            solver = cvc5.Solver(tm)

            rank = tm.mkConst(tm.getIntegerSort(), "rank_negative")

            # Rank is non-negative (property of Z-modules)
            solver.assertFormula(tm.mkTerm(cvc5.Kind.Geq, rank, tm.mkInteger(0)))

            # Negative rank (contradiction)
            solver.assertFormula(tm.mkTerm(cvc5.Kind.Lt, rank, tm.mkInteger(0)))

            is_sat = solver.checkSat().isSat()

            results["test_3_negative_rank_unsat"] = {
                "description": "Negative rank for projective module is UNSAT",
                "cvc5_sat": is_sat,
                "expected_sat": False,
                "correct": not is_sat,
            }
        except Exception as e:
            results["test_3_negative_rank_unsat"] = {"error": str(e)}

    return results


