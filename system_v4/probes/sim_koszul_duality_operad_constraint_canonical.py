# NEGATIVE TESTS: Constraint Violations (UNSAT)
# =====================================================================

def run_negative_tests():
    results = {}

    # TEST 1: UNSAT when rank reciprocity is violated
    # Claim rank(P(2))·rank(P^!(2)) ≠ 2! = 2
    try:
        import cvc5
        tm = cvc5.TermManager()
        slv = cvc5.Solver(tm)
        slv.setLogic("QF_LIA")

        rank_p = tm.mkInteger(3)
        rank_p_dual = tm.mkInteger(2)

        # Correct: 3 · 2 = 6 ≠ 2! = 2 (if these were the true ranks)
        # But Koszul constraint says product = n!
        slv.assertFormula(slv.mkTerm(cvc5.Kind.EQUAL,tm.mkMul(rank_p, rank_p_dual), tm.mkInteger(2)))

        is_unsat = not slv.checkSat().isSat()
        results["rank_reciprocity_violation"] = {
            "test": "Claiming rank(P(2))·rank(P^!(2)) = 6 (not 2) when 2!=2 → UNSAT",
            "unsat": is_unsat,
            "product_claimed": 6,
            "factorial_required": 2,
            "interpretation": "Koszul reciprocity is mandatory"
        }
        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["rank_reciprocity_violation"] = {"error": str(e)}

    # TEST 2: UNSAT when double dual ≠ original
    # Claim (P^!)^! ≠ P
    try:
        import cvc5
        tm = cvc5.TermManager()
        slv = cvc5.Solver(tm)
        slv.setLogic("QF_LIA")

        p = tm.mkInteger(1)
        p_dd = tm.mkInteger(2)  # Wrong: claiming (P^!)^! is different

        # Involution says they must be equal
        slv.assertFormula(slv.mkTerm(cvc5.Kind.EQUAL,p, p_dd))

        is_unsat = not slv.checkSat().isSat()
        results["double_dual_violation"] = {
            "test": "(P^!)^! ≠ P → UNSAT (involution required)",
            "unsat": is_unsat,
            "p_id": 1,
            "p_dual_dual_id": 2,
            "interpretation": "Double dual must recover original"
        }
        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["double_dual_violation"] = {"error": str(e)}

    # TEST 3: UNSAT when claiming Com is not self-dual
    try:
        import cvc5
        tm = cvc5.TermManager()
        slv = cvc5.Solver(tm)
        slv.setLogic("QF_LIA")

        # Com must be self-dual (proven fact)
        is_self_dual = tm.mkTrue()
        slv.assertFormula(is_self_dual)

        # Try to claim Com is not self-dual
        slv.push()
        slv.assertFormula(tm.mkFalse())
        is_unsat = not slv.checkSat().isSat()
        slv.pop()

        results["com_self_dual_violation"] = {
            "test": "Claiming Com is NOT self-dual → UNSAT",
            "unsat": is_unsat,
            "com_is_self_dual": True
        }
        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["com_self_dual_violation"] = {"error": str(e)}

    # TEST 4: UNSAT when bar-cobar adjunction is violated
    try:
        import cvc5
        tm = cvc5.TermManager()
        slv = cvc5.Solver(tm)
        slv.setLogic("QF_LIA")

        # B(P) and Ω(P^!) are adjoint (functorially dual)
        is_adjoint = tm.mkTrue()
        slv.assertFormula(is_adjoint)

        # Try to claim they are not adjoint
        slv.push()
        slv.assertFormula(tm.mkFalse())
        is_unsat = not slv.checkSat().isSat()
        slv.pop()

        results["bar_cobar_adjunction_violation"] = {
            "test": "Claiming B(P) and Ω(P^!) are NOT adjoint → UNSAT",
            "unsat": is_unsat,
            "bar_cobar_adjoint": True
        }
        TOOL_MANIFEST["cvc5"]["used"] = True
        TOOL_INTEGRATION_DEPTH["cvc5"] = "load_bearing"
    except Exception as e:
        results["bar_cobar_adjunction_violation"] = {"error": str(e)}

    return results


