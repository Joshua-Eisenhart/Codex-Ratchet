def run_negative_tests():
    """
    Negative tests: Impossible boundary operations and grading violations
    """
    results = {
        "boundary_not_self_inverse": None,
        "grading_violation_blocked": None,
        "cycles_larger_than_generators": None,
    }

    if not CVC5_AVAILABLE:
        return results

    try:
        from cvc5 import Solver, Kind

        # Test 1: Boundary operator CANNOT be self-inverse (d != d^2 identity)
        solver = Solver()

        d_squared_is_zero = solver.mkConst(solver.getBooleanSort(), "d_squared_is_zero")

        # Claim: d^2 = 0 is necessary
        solver.assertFormula(d_squared_is_zero)
        # Try to assert d^2 ≠ 0
        solver.assertFormula(solver.mkTerm(Kind.NOT, d_squared_is_zero))

        if solver.checkSat().isUnsat():
            results["boundary_not_self_inverse"] = {
                "status": "unsat",
                "interpretation": "d^2 ≠ 0 contradicts boundary operator requirement",
            }

        # Test 2: Maslov grading violation
        solver2 = Solver()

        maslov_x = solver2.mkConst(solver2.getIntegerSort(), "maslov_x")
        maslov_dx = solver2.mkConst(solver2.getIntegerSort(), "maslov_dx")
        five = solver2.mkInteger(5)
        one = solver2.mkInteger(1)

        solver2.assertFormula(solver2.mkTerm(Kind.EQUAL, maslov_x, five))
        # Try to increase degree
        solver2.assertFormula(solver2.mkTerm(Kind.EQUAL,
            maslov_dx,
            solver2.mkTerm(Kind.ADD, maslov_x, one)
        ))
        # But grading requires decrease
        solver2.assertFormula(solver2.mkTerm(Kind.EQUAL,
            maslov_dx,
            solver2.mkTerm(Kind.SUB, maslov_x, one)
        ))

        if solver2.checkSat().isUnsat():
            results["grading_violation_blocked"] = {
                "status": "unsat",
                "interpretation": "Increasing Maslov grading under d is forbidden",
            }

        # Test 3: Cycles cannot exceed generators
        solver3 = Solver()

        num_gen = solver3.mkConst(solver3.getIntegerSort(), "num_gen")
        num_cyc = solver3.mkConst(solver3.getIntegerSort(), "num_cyc")
        ten = solver3.mkInteger(10)
        zero = solver3.mkInteger(0)

        # Set up constraint: cycles <= generators
        solver3.assertFormula(solver3.mkTerm(Kind.LEQ, num_cyc, num_gen))
        # Set specific value
        solver3.assertFormula(solver3.mkTerm(Kind.EQUAL, num_gen, ten))
        # Try to violate: cycles > generators
        solver3.assertFormula(solver3.mkTerm(Kind.GT, num_cyc, num_gen))

        if solver3.checkSat().isUnsat():
            results["cycles_larger_than_generators"] = {
                "status": "unsat",
                "interpretation": "Cycle count cannot exceed generator count",
            }

    except Exception as e:
        results["boundary_not_self_inverse"] = {"error": str(e)}

    return results


