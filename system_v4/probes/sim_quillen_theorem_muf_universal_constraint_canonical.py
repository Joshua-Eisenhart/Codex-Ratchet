def test_cvc5_invalid_rank_assignment_unsat():
    """
    cvc5 proves that assigning rank(L_2) = 0 is inconsistent with
    the existence of at least one FGL (the additive one).
    """
    if cvc5 is None:
        return {"test_name": "cvc5_invalid_rank_assignment_unsat", "passed": False, "reason": "cvc5 not installed"}

    try:
        solver = cvc5.Solver()
        solver.setOption("produce-models", "true")
        solver.setLogic("QF_LIA")

        # Rank of L_2
        rank_L2 = solver.mkConst(solver.getIntegerSort(), "rank_L2")

        # Constraint: rank(L_2) >= 1 (must have at least the additive FGL)
        constraint_min_rank = solver.mkTerm(
            Kind.GEQ,
            rank_L2,
            solver.mkInteger(1)
        )

        # Violation: rank(L_2) = 0
        violation = solver.mkTerm(
            Kind.EQUAL,
            rank_L2,
            solver.mkInteger(0)
        )

        solver.assertFormula(constraint_min_rank)
        solver.assertFormula(violation)

        result = solver.checkSat()
        is_unsat = str(result) == "False"

        return {
            "test_name": "cvc5_invalid_rank_assignment_unsat",
            "passed": is_unsat,
            "description": "cvc5 proves rank(L_2)=0 violates minimum rank constraint",
            "result": str(result)
        }
    except Exception as e:
        return {"test_name": "cvc5_invalid_rank_assignment_unsat", "passed": False, "reason": str(e)}


def test_cvc5_partition_count_constraint():
    """
    cvc5 verifies partition count constraint.
    rank(L_{2n}) should correlate with partition structure.
    We test that the ranks form a consistent sequence.
    """
    if cvc5 is None:
        return {"test_name": "cvc5_partition_count_constraint", "passed": False, "reason": "cvc5 not installed"}

    try:
        solver = cvc5.Solver()
        solver.setOption("produce-models", "true")
        solver.setLogic("QF_LIA")

        # Define ranks
        rank_L0 = solver.mkInteger(1)
        rank_L2 = solver.mkInteger(1)
        rank_L4 = solver.mkInteger(2)
        rank_L6 = solver.mkInteger(5)

        # Constraint: ranks must be non-decreasing
        non_decr_1 = solver.mkTerm(Kind.LEQ, rank_L0, rank_L2)
        non_decr_2 = solver.mkTerm(Kind.LEQ, rank_L2, rank_L4)
        non_decr_3 = solver.mkTerm(Kind.LEQ, rank_L4, rank_L6)

        constraint = solver.mkTerm(Kind.AND, non_decr_1, non_decr_2, non_decr_3)
        solver.assertFormula(constraint)

        result = solver.checkSat()
        is_sat = str(result) == "True"

        return {
            "test_name": "cvc5_partition_count_constraint",
            "passed": is_sat,
            "description": "cvc5 satisfies non-decreasing rank constraint",
            "result": str(result)
        }
    except Exception as e:
        return {"test_name": "cvc5_partition_count_constraint", "passed": False, "reason": str(e)}


def test_symbolic_non_universal_fgl_fails():
    """
    Show that a "non-universal" FGL cannot be the FGL of MU.
    E.g., the additive FGL x+y is universal (for characteristic 0).
    But an incomplete FGL (missing some structure) would not be.

    Test: the additive FGL IS universal.
    """
    x, y, z = symbols('x y z', real=True)

    # Additive FGL
    F_add = lambda a, b: a + b

    # Check universality properties:
    # 1. Identity: F(x,0) = x
    id_left = expand(F_add(x, 0) - x) == 0
    # 2. Associativity: F(F(x,y),z) = F(x,F(y,z))
    assoc = expand(F_add(F_add(x, y), z) - F_add(x, F_add(y, z))) == 0
    # 3. Commutativity: F(x,y) = F(y,x)
    comm = expand(F_add(x, y) - F_add(y, x)) == 0

    all_properties_hold = id_left and assoc and comm

    return {
        "test_name": "symbolic_non_universal_fgl_fails",
        "passed": all_properties_hold,
        "description": "Additive FGL is universal (satisfies all required properties)",
        "identity": id_left,
        "associativity": assoc,
        "commutativity": comm
    }


