        "r3_octonion_spinor_dim" => r3_summary["octonion_spinor_dim"],
        "local_spinor_dim" => size(gammas[1], 1),
        "local_generated_rank_from_6_quantumoptics_gammas" => local_rank,
        "matches_r3_rank" => local_rank == r3_summary["octonion_cl6_rank"],
        "matches_r3_spinor_dim" => size(gammas[1], 1) == r3_summary["octonion_spinor_dim"],
    )
end

function matrix_anticommutation_report(gammas)
    dim = size(gammas[1], 1)
    ident = Matrix{ComplexF64}(LinearAlgebra.I, dim, dim)
    max_residual = 0.0
    failures = Any[]
    for i in eachindex(gammas), j in eachindex(gammas)
        target = i == j ? 2.0 .* ident : zeros(ComplexF64, dim, dim)
        residual = norm(gammas[i] * gammas[j] + gammas[j] * gammas[i] - target)
        max_residual = max(max_residual, Float64(residual))
        if residual > TOL
            push!(failures, Dict{String,Any}("i" => i, "j" => j, "residual" => Float64(residual)))
        end
    end
    Dict{String,Any}("max_residual" => max_residual, "failures" => failures, "pass" => isempty(failures))
end

function cliffordalgebras_report()
    cl6 = CliffordAlgebra(6, 0)
    gens = [getproperty(cl6, Symbol("e$i")) for i in 1:6]
    unit = one(gens[1])
    raw_ps = reduce(*, gens)
    anticommutation_failures = Any[]
    max_residual = 0.0
    for i in 1:6, j in 1:6
        lhs = gens[i] * gens[j] + gens[j] * gens[i]
        rhs = (i == j ? 2 : 0) * unit
        residual = Float64(CliffordAlgebras.norm(lhs - rhs))
        max_residual = max(max_residual, residual)
        if residual > TOL
            push!(anticommutation_failures, Dict{String,Any}("i" => i, "j" => j, "residual" => residual))
        end
    end
    raw_square_residual = Float64(CliffordAlgebras.norm(raw_ps * raw_ps + unit))
    Dict{String,Any}(
        "package" => "CliffordAlgebras",
        "signature" => "Cl(6,0)",
        "generator_count" => length(gens),
        "raw_pseudoscalar" => string(raw_ps),
        "raw_pseudoscalar_square" => string(raw_ps * raw_ps),
        "raw_pseudoscalar_square_minus_negative_unit_residual" => raw_square_residual,
        "anticommutation" => Dict{String,Any}(
            "max_residual" => max_residual,
            "failures" => anticommutation_failures,
            "pass" => isempty(anticommutation_failures),
        ),
    )
end

function z3_projector_dim_proof(trace_gamma7::Int, control_trace::Int)
    main = Z3.Solver()
    p = Z3.IntVar("plus_dim")
    m = Z3.IntVar("minus_dim")
    Z3.add(main, z3_add(Z3.Expr[p, m]) == Z3.IntVal(8))
    Z3.add(main, z3_sub(p, m) == Z3.IntVal(trace_gamma7))
    Z3.add(main, Z3.Or(Z3.Expr[Z3.Not(p == Z3.IntVal(4)), Z3.Not(m == Z3.IntVal(4))]))
    main_status = string(Z3.check(main))

    control = Z3.Solver()
    cp = Z3.IntVar("control_plus_dim")
    cm = Z3.IntVar("control_minus_dim")
    Z3.add(control, z3_add(Z3.Expr[cp, cm]) == Z3.IntVal(8))
    Z3.add(control, z3_sub(cp, cm) == Z3.IntVal(control_trace))
    Z3.add(control, Z3.Or(Z3.Expr[Z3.Not(cp == Z3.IntVal(4)), Z3.Not(cm == Z3.IntVal(4))]))
    control_status = string(Z3.check(control))

    Dict{String,Any}(
        "encoding" => "Int plus/minus dimensions satisfy plus+minus=8 and plus-minus=Tr(gamma7); assert not 4/4.",
        "main_not_4_4_verdict" => main_status,
        "control_identity_not_4_4_verdict" => control_status,
        "main_proved_4_4" => main_status == "unsat",
        "identity_control_flips" => control_status == "sat",
    )
end

function class_partition(signatures::Vector{Float64}, prefix::String)
    groups = Dict{String,Vector{String}}()
    for (idx, sig) in enumerate(signatures)
        key = string(round(sig; digits=12))
        if !haskey(groups, key)
            groups[key] = String[]
        end
        push!(groups[key], "basis_$(idx - 1)")
    end
    classes = Any[]
    for (class_idx, key) in enumerate(sort(collect(keys(groups))))
        push!(classes, Dict{String,Any}(
            "class_id" => "$(prefix)_q$(class_idx - 1)",
            "signature" => [parse(Float64, key)],
            "members" => sort(groups[key]),
        ))
    end
    classes
end

function constraints_report(dim::Int)
    details = Any[]
    for idx in 1:dim
        v = zeros(ComplexF64, dim)
        v[idx] = 1.0 + 0.0im
        rho = v * v'
        eigs = eigvals(Hermitian((rho + rho') / 2))
        push!(details, Dict{String,Any}(
            "id" => "basis_$(idx - 1)",
            "trace_residual" => abs(real(tr(rho)) - 1.0),
            "hermitian_residual" => norm(rho - rho'),
            "min_eigenvalue" => minimum(real.(eigs)),
            "normalization_residual" => abs(real(v' * v) - 1.0),
            "psd" => minimum(real.(eigs)) >= -TOL,
        ))
    end
    Dict{String,Any}(
        "trace_one" => all(row["trace_residual"] <= TOL for row in details),
        "hermitian" => all(row["hermitian_residual"] <= TOL for row in details),
        "psd" => all(row["psd"] for row in details),
        "normalized" => all(row["normalization_residual"] <= TOL for row in details),
        "details" => details,
    )
end

