function z3_add(args::Vector{Z3.Expr})
    ctx = args[1].ctx
    Z3.Expr(ctx, Z3.Libz3.Z3_mk_add(Z3.ctx_ref(args[1]), length(args), map(Z3.as_ast, args)))
end

function z3_sub(left::Z3.Expr, right::Z3.Expr)
    ctx = left.ctx
    Z3.Expr(ctx, Z3.Libz3.Z3_mk_sub(Z3.ctx_ref(left), 2, map(Z3.as_ast, [left, right])))
end

function spin_basis_ops()
    b = SpinBasis(1//2)
    Dict(
        "I" => identityoperator(b),
        "X" => sigmax(b),
        "Y" => sigmay(b),
        "Z" => sigmaz(b),
    )
end

function tensor_matrix(a, b, c)
    Matrix(tensor(a, b, c).data)
end

function quantumoptics_gamma_matrices()
    ops = spin_basis_ops()
    i2 = ops["I"]
    x = ops["X"]
    y = ops["Y"]
    z = ops["Z"]
    [
        tensor_matrix(x, i2, i2),
        tensor_matrix(y, i2, i2),
        tensor_matrix(z, x, i2),
        tensor_matrix(z, y, i2),
        tensor_matrix(z, z, x),
        tensor_matrix(z, z, y),
    ]
end

