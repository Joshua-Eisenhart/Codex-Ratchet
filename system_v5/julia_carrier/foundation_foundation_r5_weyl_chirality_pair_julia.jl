# Same generated-rank technique R3 uses on its octonion left-multiplication
# matrices (foundation_r3_octonion_cl6_link_xhigh_julia.jl): the rank of the
# matrix algebra generated by all 2^k products of k anticommuting generators.
# Applied here to this rung's own 6 QuantumOptics gamma matrices so the
# independently-built 3-qubit Cl(6)-type carrier is cross-checked against
# R3's admitted Cl(0,6) octonion-linked rank/spinor-dimension, not just
# judged consistent by code inspection.
function generated_rank(mats::Vector{Matrix{ComplexF64}}, generator_count::Int)
    dim = size(mats[1], 1)
    cols = Vector{ComplexF64}[]
    for mask in 0:(2^generator_count - 1)
        acc = Matrix{ComplexF64}(LinearAlgebra.I, dim, dim)
        for idx in 1:generator_count
            if ((mask >> (idx - 1)) & 1) == 1
                acc = acc * mats[idx]
            end
        end
        push!(cols, vec(acc))
    end
    mat = hcat(cols...)
    singular = svdvals(mat)
    max_s = isempty(singular) ? 0.0 : maximum(singular)
    tol = max(size(mat)...) * eps(Float64) * max_s * 100.0
    count(>(tol), singular)
end

function r3_provenance_check(r3::AbstractDict, gammas::Vector{Matrix{ComplexF64}})
