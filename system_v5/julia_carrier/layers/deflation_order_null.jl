# =====================================================================================
# deflation_order_null.jl
#   classification = deflation_ordernull_poc ; promotion_allowed = false
# -------------------------------------------------------------------------------------
# Apply Grok's deflation control to the ORDER-NULL / order-sensitivity claim.
#
# GENUINE construction:
#   Reuse the exact density-operator channel definitions from order_null_killtest.jl:
#   Ti, Fi, WeylL, Te, Fe, WeylR composed forward vs reversed on the same random rho set.
#
# DEFLATED construction:
#   Fix one Hopf base H0. Vary only spin^c / connection-lift choices on that base.
#   No channel type changes, no layer stack, no distinct terrain/Weyl/pinch/rotation
#   composition. The admissible lift family is generated by one base Hamiltonian H0 and
#   same-base dephasing/connection variants. If that single-base lift family reproduces
#   the genuine fwd-vs-rev gap and order-discriminating irreversibility, ORDER-NULL
#   deflates. If it cannot, the order gap survives as a genuine multi-channel order DOF.
#
# CLAIM CEILING:
#   This is a bounded deflation POC only. It does NOT assert layer completion, manifold
#   admission, bridge/Xi/Phi0/Axis0, flux, FEP, physics, or ratchet-edge admission.
#   promotion_allowed=false.
# =====================================================================================

using LinearAlgebra
