# sympy EXACT proofs                                                            #
# --------------------------------------------------------------------------- #
def sympy_exact_cl3() -> dict[str, Any]:
    """EXACT symbolic algebra of Cl(3): represent generators by the real 8x8
    left-regular representation built from the SAME structure constants and prove
    the relations identically. We instead use a faithful 2x2 complex (Pauli)
    representation of Cl(3): e_i = sigma_i. sigma_i^2 = I, sigma_i sigma_j =
    -sigma_j sigma_i (i!=j), and the even part gives quaternions."""
    I2 = sp.eye(2)
    sx = sp.Matrix([[0, 1], [1, 0]])
    sy = sp.Matrix([[0, -sp.I], [sp.I, 0]])
    sz = sp.Matrix([[1, 0], [0, -1]])
    e = [sx, sy, sz]
    # e_i^2 == I (Euclidean signature, since sigma_i^2 = identity)
    sq_ok = all(sp.simplify(ei * ei - I2) == sp.zeros(2, 2) for ei in e)
    # {e_i, e_j} == 2 delta_ij I
    anti_ok = True
    for a in range(3):
        for b in range(3):
            anti = e[a] * e[b] + e[b] * e[a]
            target = (2 if a == b else 0) * I2
            if sp.simplify(anti - target) != sp.zeros(2, 2):
                anti_ok = False
    # pseudoscalar I3 = e1 e2 e3 = sx sy sz = i*I -> I3^2 = -I
    I3 = sp.simplify(sx * sy * sz)
    I3_sq = sp.simplify(I3 * I3)
    I3_sq_is_minus = sp.simplify(I3_sq + I2) == sp.zeros(2, 2)
    # I3 commutes with everything (it is i*I)
    I3_central = all(sp.simplify(I3 * ei - ei * I3) == sp.zeros(2, 2) for ei in e)
    # quaternions: i=-e23, j=-e31, k=-e12 with e_ij = e_i e_j
    e23 = sx * sy  # NOTE: in Pauli rep e2 e3 = sy sz ; fix below
    # use proper bivectors e_i e_j with the actual (sx,sy,sz)=(e1,e2,e3)
    e1, e2, e3 = sx, sy, sz
    qi = sp.simplify(-(e2 * e3))
    qj = sp.simplify(-(e3 * e1))
    qk = sp.simplify(-(e1 * e2))
    i2 = sp.simplify(qi * qi)
    j2 = sp.simplify(qj * qj)
    k2 = sp.simplify(qk * qk)
    ijk = sp.simplify(qi * qj * qk)
    quat_relations = (sp.simplify(i2 + I2) == sp.zeros(2, 2)
                      and sp.simplify(j2 + I2) == sp.zeros(2, 2)
                      and sp.simplify(k2 + I2) == sp.zeros(2, 2)
                      and sp.simplify(ijk + I2) == sp.zeros(2, 2))
    ij_eq_k = sp.simplify(qi * qj - qk) == sp.zeros(2, 2)
    jk_eq_i = sp.simplify(qj * qk - qi) == sp.zeros(2, 2)
    ki_eq_j = sp.simplify(qk * qi - qj) == sp.zeros(2, 2)
    # rotor angle EXACT: R = cos(t/2) - sin(t/2) e1 e2 rotates e1 by t in (e1,e2)
    t = sp.symbols("t", real=True)
    B = e1 * e2
    R = sp.cos(t / 2) * I2 - sp.sin(t / 2) * B
    Rrev = sp.cos(t / 2) * I2 + sp.sin(t / 2) * B  # reverse: ~B = -B
    rotated = sp.simplify(R * e1 * Rrev)
    expected = sp.simplify(sp.cos(t) * e1 + sp.sin(t) * e2)
    rotor_exact = sp.simplify(rotated - expected) == sp.zeros(2, 2)
    return {
        "e_i_squared_is_identity_exact": bool(sq_ok),
        "anticommutator_2delta_exact": bool(anti_ok),
        "pseudoscalar_I3_squared": str(I3_sq.tolist()),
        "pseudoscalar_I3_squared_is_minus_one_exact": bool(I3_sq_is_minus),
        "pseudoscalar_central_exact": bool(I3_central),
        "quaternion_relations_i2j2k2ijk_minus1_exact": bool(quat_relations),
        "quaternion_ij_eq_k_exact": bool(ij_eq_k),
        "quaternion_jk_eq_i_exact": bool(jk_eq_i),
        "quaternion_ki_eq_j_exact": bool(ki_eq_j),
        "rotor_rotates_by_theta_exact": bool(rotor_exact),
    }


