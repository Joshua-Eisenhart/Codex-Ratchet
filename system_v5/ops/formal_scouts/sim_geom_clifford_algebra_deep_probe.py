# z3: anticommutator structure forces {e_i,e_j} = 2 delta_ij                    #
# --------------------------------------------------------------------------- #
def z3_anticommutator_certificate(cl: CliffordTorch) -> dict[str, Any]:
    """Feed z3 the numeric anticommutator entries a_ij = (e_i e_j + e_j e_i)_0
    (scalar part) computed by the torch product, and the target t_ij=2 delta_ij.
    Assert NOT(all a_ij == t_ij); UNSAT => the structure satisfies the Clifford
    Gram relation. (The grade-0 part of e_i e_j + e_j e_i is exactly the metric.)"""
    s = z3.Solver()
    constraints = []
    target_match = []
    for i in range(cl.n):
        ei = cl.blade((i,))
        for j in range(cl.n):
            ej = cl.blade((j,))
            anti = cl.product(ei, ej) + cl.product(ej, ei)
            a0 = float(anti[0].item())  # scalar part = 2 delta_ij
            var = z3.Real(f"a_{i}_{j}")
            s.add(var == z3.RealVal(repr(a0)))
            tgt = 2 if i == j else 0
            target_match.append(var == z3.RealVal(tgt))
    s.add(z3.Not(z3.And(*target_match)))
    status = str(s.check())
    return {"negation_status": status, "pass": status == "unsat"}


# --------------------------------------------------------------------------- #
# cvc5: pseudoscalar I^2 == -1                                                  #
# --------------------------------------------------------------------------- #
def cvc5_pseudoscalar_certificate(cl: CliffordTorch) -> dict[str, Any]:
    """Compute I = e_1...e_n via torch; I^2 is a scalar for odd n (Cl(3): I^2=-1).
    Feed the scalar coefficient of I^2 to cvc5, assert NOT(coeff == known), check
    UNSAT. For Cl(3) the known value is -1."""
    # build pseudoscalar
    I = cl.blade(tuple(range(cl.n)))
    I2 = cl.product(I, I)
    coeff = float(I2[0].item())  # scalar part
    # also confirm I2 has no non-scalar parts (for n=3 it is purely scalar)
    nonscalar = float(torch.linalg.vector_norm(I2[1:]).item())
    # known: for Cl(n) Euclidean, I^2 = (-1)^{n(n-1)/2}. For n=3: (-1)^3 = -1.
    known = (-1) ** (cl.n * (cl.n - 1) // 2)
    slv = cvc5.Solver()
    slv.setOption("produce-models", "false")
    slv.setLogic("QF_NRA")
    R = slv.getRealSort()

    def rv(x: float):
        frac = sp.Rational(x).limit_denominator(10 ** 12)
        num, den = sp.fraction(frac)
        return slv.mkReal(int(num), int(den)) if int(den) != 1 else slv.mkReal(int(num))

    C = slv.mkConst(R, "c")
    slv.assertFormula(slv.mkTerm(Kind.EQUAL, C, rv(coeff)))
    eq_known = slv.mkTerm(Kind.EQUAL, C, slv.mkReal(int(known)))
    slv.assertFormula(slv.mkTerm(Kind.NOT, eq_known))
    res = slv.checkSat()
    status = "unsat" if res.isUnsat() else ("sat" if res.isSat() else "unknown")
    return {"negation_status": status, "pass": res.isUnsat(),
            "I_squared_scalar": coeff, "I_squared_nonscalar_norm": nonscalar,
            "known_I_squared": known}


# --------------------------------------------------------------------------- #
# torch product == clifford library product (full blade table)                  #
# --------------------------------------------------------------------------- #
def cross_check_library_full_table(cl: CliffordTorch) -> dict[str, Any]:
    """Compare the torch structure-constant product against the clifford library
    on every pair of basis blades (full 2^n x 2^n table)."""
    layout, _ = clifford_layout(cl.n)
    max_err = 0.0
    n_pairs = 0
    for a in range(cl.dim):
        ea_t = torch.zeros(cl.dim, dtype=RTYPE)
        ea_t[a] = 1.0
        ea_c = torch_blade_to_clifford(cl, layout, ea_t)
        for b in range(cl.dim):
            eb_t = torch.zeros(cl.dim, dtype=RTYPE)
            eb_t[b] = 1.0
            prod_t = cl.product(ea_t, eb_t)
            eb_c = torch_blade_to_clifford(cl, layout, eb_t)
            prod_c = ea_c * eb_c
            prod_c_t = clifford_mv_to_torch(cl, layout, prod_c)
            err = float(torch.linalg.vector_norm(prod_t - prod_c_t).item())
            max_err = max(max_err, err)
            n_pairs += 1
    return {"max_abs_diff": max_err, "n_blade_pairs": n_pairs,
            "matches_library": max_err < TOL}


# --------------------------------------------------------------------------- #
# torch product == quimb tensor-network contraction of structure tensor         #
# --------------------------------------------------------------------------- #
def quimb_structure_tensor_check(cl: CliffordTorch, seed: int) -> dict[str, Any]:
    """Build the rank-3 structure tensor T[c,a,b] s.t. (x*y)_c = sum_ab T[c,a,b]
    x_a y_b, then contract two random multivectors with quimb and compare to the
    torch product."""
    d = cl.dim
    T = torch.zeros((d, d, d), dtype=RTYPE)
    for a in range(d):
        for b in range(d):
            s = cl.sign_tab[a, b]
            if s == 0:
                continue
            c = int(cl.idx_tab[a, b].item())
            T[c, a, b] = s
    gen = torch.Generator().manual_seed(seed)
    x = torch.randn(d, generator=gen, dtype=RTYPE)
    y = torch.randn(d, generator=gen, dtype=RTYPE)
    # quimb tensor-network contraction
    Tt = qtn.Tensor(T.numpy(), inds=("c", "a", "b"))
    Xt = qtn.Tensor(x.numpy(), inds=("a",))
    Yt = qtn.Tensor(y.numpy(), inds=("b",))
    tn = Tt & Xt & Yt
    out_q = torch.as_tensor(tn.contract(output_inds=("c",)).data, dtype=RTYPE)
    out_t = cl.product(x, y)
    err = float(torch.linalg.vector_norm(out_q - out_t).item())
    return {"seed": seed, "max_abs_diff": err, "matches_torch": err < TOL}


# --------------------------------------------------------------------------- #
# Associativity over the full blade table (torch)                               #
# --------------------------------------------------------------------------- #
def associativity_check(cl: CliffordTorch) -> dict[str, Any]:
    """(e_a e_b) e_c == e_a (e_b e_c) on all blade triples."""
    max_err = 0.0
    n = 0
    d = cl.dim
    for a in range(d):
        ea = torch.zeros(d, dtype=RTYPE); ea[a] = 1.0
        for b in range(d):
            eb = torch.zeros(d, dtype=RTYPE); eb[b] = 1.0
            ab = cl.product(ea, eb)
            for c in range(d):
                ec = torch.zeros(d, dtype=RTYPE); ec[c] = 1.0
                left = cl.product(ab, ec)
                right = cl.product(ea, cl.product(eb, ec))
                err = float(torch.linalg.vector_norm(left - right).item())
                max_err = max(max_err, err)
                n += 1
    return {"max_abs_diff": max_err, "n_triples": n, "associative": max_err < TOL}


# --------------------------------------------------------------------------- #
# Rotor rotation angle: numeric (torch) + induced SO(3) (geomstats + e3nn)      #
# --------------------------------------------------------------------------- #
def induced_rotation_matrix(cl: CliffordTorch, R: torch.Tensor) -> torch.Tensor:
    """3x3 (for Cl(3)) matrix of the rotor action on grade-1 basis vectors."""
    M = torch.zeros((cl.n, cl.n), dtype=RTYPE)
    for j in range(cl.n):
        ej = cl.blade((j,))
        rot = rotate_vector(cl, R, ej)
        comps = vector_components(cl, rot)
        M[:, j] = comps
    return M


def rotor_angle_sweep_cl3() -> dict[str, Any]:
    """For Cl(3): for each angle and each coordinate plane (12,13,23), build the
    rotor, rotate a random vector, and check the rotation angle equals theta. Then
    certify the 3x3 induced matrix is in SO(3) via geomstats AND e3nn."""
    cl = CliffordTorch(3)
    SO3 = SpecialOrthogonal(n=3)
    planes = [(0, 1), (0, 2), (1, 2)]
    max_angle_err = 0.0
    max_norm_err = 0.0
    so3_geomstats_all = True
    e3nn_results = []
    for theta in ANGLES:
        for (i, j) in planes:
            R = rotor_on_plane(cl, i, j, theta)
            # rotate a vector that lies in the plane (pure rotation by theta)
            comps = torch.zeros(3, dtype=RTYPE)
            comps[i] = 1.0
            v = cl.vector(comps)
            rot = rotate_vector(cl, R, v)
            rc = vector_components(cl, rot)
            # angle between v_in (in plane) and rot, restricted to plane
            cos_ang = float(rc[i].item())   # since |v|=1 and rot stays unit
            sin_ang = float(rc[j].item())
            ang = math.atan2(sin_ang, cos_ang) % (2 * math.pi)
            target = theta % (2 * math.pi)
            err = min(abs(ang - target), 2 * math.pi - abs(ang - target))
            max_angle_err = max(max_angle_err, err)
            # norm preserved
            max_norm_err = max(max_norm_err,
                               abs(float(torch.linalg.vector_norm(rc).item()) - 1.0))
            # induced SO(3) matrix
            M = induced_rotation_matrix(cl, R)
            belongs = bool(SO3.belongs(M, atol=1e-9))
            so3_geomstats_all = so3_geomstats_all and belongs
    # e3nn certification on one representative matrix per plane (theta=pi/3)
    for (i, j) in planes:
        R = rotor_on_plane(cl, i, j, math.pi / 3)
        M = induced_rotation_matrix(cl, R).to(torch.float32)
        det = float(torch.det(M).item())
        orth = float(torch.linalg.matrix_norm(M @ M.T - torch.eye(3)).item())
        if abs(det - 1.0) < TOL_E3NN and orth < TOL_E3NN:
            a, b, c = o3.matrix_to_angles(M)
            Mrec = o3.angles_to_matrix(a, b, c)
            recon = float(torch.linalg.matrix_norm(Mrec - M).item())
            D = o3.Irrep("1o").D_from_angles(a, b, c)
            d_match = float(torch.linalg.matrix_norm(D - M).item())
            ok = recon < TOL_E3NN and d_match < 1e-4
        else:
            recon, d_match, ok = None, None, False
        e3nn_results.append({"plane": [i, j], "det": det, "orth_defect": orth,
                             "recon_err": recon, "wigner_l1_match": d_match, "pass": ok})
    return {
        "max_angle_err": max_angle_err,
        "max_norm_err": max_norm_err,
        "so3_geomstats_all_belong": so3_geomstats_all,
        "e3nn_results": e3nn_results,
        "e3nn_all_pass": all(r["pass"] for r in e3nn_results),
        "n_angles": len(ANGLES), "n_planes": len(planes),
    }


# --------------------------------------------------------------------------- #
# Quaternion subalgebra numeric (torch) + clifford library                      #
# --------------------------------------------------------------------------- #
def quaternion_subalgebra_check() -> dict[str, Any]:
    """i=-e23, j=-e31, k=-e12 in Cl(3) satisfy i^2=j^2=k^2=ijk=-1, ij=k, etc.
    Computed in torch AND verified against the clifford library."""
    cl = CliffordTorch(3)
    qi = -cl.blade((1, 2))   # -e23  (0-based gens 1,2)
    qj = -cl.blade((2, 0))   # -e31  -> e3 e1 = -(e1 e3); blade((2,0)) handles order
    qk = -cl.blade((0, 1))   # -e12

    def sq(x):
        return cl.product(x, x)

    i2 = sq(qi); j2 = sq(qj); k2 = sq(qk)
    ijk = cl.product(cl.product(qi, qj), qk)
    minus1 = cl.scalar(-1.0)
    errs = {
        "i2": float(torch.linalg.vector_norm(i2 - minus1).item()),
        "j2": float(torch.linalg.vector_norm(j2 - minus1).item()),
        "k2": float(torch.linalg.vector_norm(k2 - minus1).item()),
        "ijk": float(torch.linalg.vector_norm(ijk - minus1).item()),
        "ij_eq_k": float(torch.linalg.vector_norm(cl.product(qi, qj) - qk).item()),
        "jk_eq_i": float(torch.linalg.vector_norm(cl.product(qj, qk) - qi).item()),
        "ki_eq_j": float(torch.linalg.vector_norm(cl.product(qk, qi) - qj).item()),
    }
    torch_ok = all(v < TOL for v in errs.values())
    # clifford library cross-check
    layout, blades = clifford_layout(3)
    e1, e2, e3 = blades["e1"], blades["e2"], blades["e3"]
    li = -(e2 * e3); lj = -(e3 * e1); lk = -(e1 * e2)
    lib_ok = (
        (li * li + 1) == 0 * e1 and (lj * lj + 1) == 0 * e1 and (lk * lk + 1) == 0 * e1
        and (li * lj * lk + 1) == 0 * e1
        and (li * lj - lk) == 0 * e1 and (lj * lk - li) == 0 * e1 and (lk * li - lj) == 0 * e1
    )
    return {"torch_errs": errs, "torch_quaternions_ok": torch_ok,
            "clifford_library_quaternions_ok": bool(lib_ok)}


# --------------------------------------------------------------------------- #
# Generator squares / anticommutation numeric (torch) for Cl(3) and Cl(6)       #
# --------------------------------------------------------------------------- #
def generator_relations(cl: CliffordTorch) -> dict[str, Any]:
    one = cl.scalar(1.0)
    sq_errs = []
    anti_errs = []
    for i in range(cl.n):
        ei = cl.blade((i,))
        sq = cl.product(ei, ei)
        sq_errs.append(float(torch.linalg.vector_norm(sq - one).item()))
        for j in range(cl.n):
            ej = cl.blade((j,))
            anti = cl.product(ei, ej) + cl.product(ej, ei)
            target = cl.scalar(2.0) if i == j else cl.scalar(0.0)
            anti_errs.append(float(torch.linalg.vector_norm(anti - target).item()))
            if i != j:
                comm = cl.product(ei, ej) + cl.product(ej, ei)  # should be 0
    return {
        "n": cl.n, "dim": cl.dim,
        "max_e_i_squared_err": max(sq_errs),
        "max_anticommutator_err": max(anti_errs),
        "e_i_squared_is_one": max(sq_errs) < TOL,
        "anticommutator_is_2delta": max(anti_errs) < TOL,
        "dim_is_2_to_n": cl.dim == (1 << cl.n),
    }


# --------------------------------------------------------------------------- #
# NEGATIVES                                                                     #
# --------------------------------------------------------------------------- #
def negative_commutative_collapse() -> dict[str, Any]:
    """Force the generators to COMMUTE (e_i e_j = + e_j e_i). Then the
    anticommutator {e_i,e_j} = 2 e_i e_j != 0 for i!=j, so the Gram relation
    {e_i,e_j}=2 delta_ij is destroyed; the rotor no longer rotates (R v ~R = v),
    and the quaternion product collapses (ijk != -1)."""
    cl = CliffordTorch(3)
    # commutative product: drop the reorder sign; just OR the masks with sig on
    # repeats, sign forced +1 for distinct gens.

    def comm_product(x: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
        out = torch.zeros(cl.dim, dtype=RTYPE)
        for a in range(cl.dim):
            if x[a] == 0:
                continue
            for b in range(cl.dim):
                if y[b] == 0:
                    continue
                # commutative: repeated gens square to +1, distinct just merge,
                # sign always +1 (no anticommutation)
                inter = a & b
                # any shared generator squares to 1 (sig=+1); result = symdiff
                res = a ^ b
                out[res] = out[res] + x[a] * y[b]
        return out

    e1 = cl.blade((0,)); e2 = cl.blade((1,))
    anti = comm_product(e1, e2) + comm_product(e2, e1)
    # off-diagonal anticommutator scalar part: in the genuine algebra this is 0
    anti_offdiag = float(torch.linalg.vector_norm(anti).item())
    # rotor built with commutative product fails to rotate
    R = cl.scalar(math.cos(math.pi / 4)) - math.sin(math.pi / 4) * cl.blade((0, 1))
    v = cl.vector(torch.tensor([1.0, 0.0, 0.0], dtype=RTYPE))
    # use commutative sandwich
    rot = comm_product(comm_product(R, v), cl.reverse(R))
    rc = vector_components(cl, rot)
    moved = float(torch.linalg.vector_norm(rc - torch.tensor([1.0, 0.0, 0.0], dtype=RTYPE)).item())
    # genuine rotor for comparison
    R_true = rotor_on_plane(cl, 0, 1, math.pi / 4)
    rot_true = rotate_vector(cl, R_true, v)
    rc_true = vector_components(cl, rot_true)
    moved_true = float(torch.linalg.vector_norm(rc_true - torch.tensor([1.0, 0.0, 0.0], dtype=RTYPE)).item())
    return {
        "commutative_anticommutator_offdiag_norm": anti_offdiag,
        "true_anticommutator_offdiag_is_zero": True,  # by construction in real alg
        "commutative_rotor_moved_vector_by": moved,
        "true_rotor_moved_vector_by": moved_true,
        # KILL: commutative version does NOT produce the genuine rotation
        "kills_signature": (anti_offdiag > TOL) and (abs(moved - moved_true) > 0.1),
    }


def negative_scalar_flatten() -> dict[str, Any]:
    """Project every multivector to its grade-0 (scalar) part before multiplying.
    The geometric product collapses to ordinary scalar multiplication; all
    bivector/rotor/quaternion structure vanishes (a rotor flattens to its scalar
    cos(theta/2), which cannot rotate)."""
    cl = CliffordTorch(3)
    R = rotor_on_plane(cl, 0, 1, math.pi / 3)
    R_flat = cl.grade0(R)  # only cos(theta/2)
    v = cl.vector(torch.tensor([1.0, 0.0, 0.0], dtype=RTYPE))
    # flattened "rotation": scalar * v * scalar -- pure scaling, no rotation
    rot_flat = cl.product(cl.product(R_flat, v), cl.reverse(R_flat))
    rc_flat = vector_components(cl, rot_flat)
    # genuine
    rot = rotate_vector(cl, R, v)
    rc = vector_components(cl, rot)
    # flattened result has zero e2 component (no rotation into the plane)
    e2_flat = abs(float(rc_flat[1].item()))
    e2_true = abs(float(rc[1].item()))
    return {
        "flattened_e2_component": e2_flat,
        "true_e2_component": e2_true,
        "kills_signature": e2_flat < TOL and e2_true > 0.1,
    }


def negative_degenerate_signature() -> dict[str, Any]:
    """Set the signature to e_i^2 = 0 (null/degenerate generators). Then blades
    are nilpotent, the pseudoscalar I^2 = 0 (not -1), and the Euclidean Clifford
    signature is destroyed."""
    cl_deg = CliffordTorch(3, signature=(0, 0, 0))
    e1 = cl_deg.blade((0,))
    e1_sq = cl_deg.product(e1, e1)  # should be 0
    I = cl_deg.blade((0, 1, 2))
    I_sq = cl_deg.product(I, I)
    cl_euc = CliffordTorch(3)
    I_euc = cl_euc.blade((0, 1, 2))
    I_euc_sq = cl_euc.product(I_euc, I_euc)
    return {
        "degenerate_e1_squared_norm": float(torch.linalg.vector_norm(e1_sq).item()),
        "degenerate_pseudoscalar_squared_scalar": float(I_sq[0].item()),
        "euclidean_pseudoscalar_squared_scalar": float(I_euc_sq[0].item()),
        # KILL: degenerate I^2 == 0 while Euclidean I^2 == -1
        "kills_signature": (abs(float(I_sq[0].item())) < TOL
                            and abs(float(I_euc_sq[0].item()) + 1.0) < TOL),
    }


