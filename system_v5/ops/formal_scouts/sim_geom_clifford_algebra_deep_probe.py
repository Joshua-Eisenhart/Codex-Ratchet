# --------------------------------------------------------------------------- #
# First-principles geometric product in torch (structure-constant tensor)      #
# --------------------------------------------------------------------------- #
class CliffordTorch:
    """Real Euclidean Clifford algebra Cl(n) built from first principles in torch.

    Basis blades are indexed by integer bitmasks over {0..n-1}. The blade e_S is
    the *ordered* product e_{i_1} e_{i_2} ... with i_1 < i_2 < ... The geometric
    product of two ordered blades is computed by merging the two index lists,
    counting transpositions (each adjacent swap of distinct generators contributes
    a -1 from anticommutation) and squaring repeated generators (each repeat
    contributes the signature value, +1 for Euclidean). All of this lives in a
    (2^n, 2^n) structure-constant table M with sign in {-1,0,+1}, stored as a
    torch.float64 tensor, plus a (2^n, 2^n) integer "result blade" index table.
    """

    def __init__(self, n: int, signature: tuple[int, ...] | None = None):
        self.n = n
        self.dim = 1 << n
        # signature[i] = e_i^2 in {+1 (Euclidean), -1, 0 (degenerate)}
        self.sig = signature if signature is not None else tuple([1] * n)
        sign_tab = torch.zeros((self.dim, self.dim), dtype=RTYPE)
        idx_tab = torch.zeros((self.dim, self.dim), dtype=torch.int64)
        for a in range(self.dim):
            for b in range(self.dim):
                s, res = self._blade_product(a, b)
                sign_tab[a, b] = float(s)
                idx_tab[a, b] = res
        self.sign_tab = sign_tab
        self.idx_tab = idx_tab

    def _blade_product(self, a: int, b: int) -> tuple[int, int]:
        """Geometric product of blade-bitmask a with blade-bitmask b.
        Returns (sign, result_bitmask). sign in {-1,0,+1}."""
        # list generators of a (ascending), then b (ascending)
        la = [i for i in range(self.n) if (a >> i) & 1]
        lb = [i for i in range(self.n) if (b >> i) & 1]
        seq = la + lb
        sign = 1
        # bubble-sort 'seq' to ascending order, counting swaps of DISTINCT gens.
        arr = seq[:]
        i = 0
        # stable insertion sort counting adjacent transpositions
        m = len(arr)
        for p in range(1, m):
            q = p
            while q > 0 and arr[q - 1] > arr[q]:
                arr[q - 1], arr[q] = arr[q], arr[q - 1]
                sign = -sign
                q -= 1
        # now arr is sorted ascending; collapse equal adjacent pairs e_i e_i = sig_i
        out: list[int] = []
        k = 0
        while k < len(arr):
            if k + 1 < len(arr) and arr[k] == arr[k + 1]:
                sign *= self.sig[arr[k]]
                if sign == 0:
                    return 0, 0
                k += 2
            else:
                out.append(arr[k])
                k += 1
        res = 0
        for g in out:
            res |= (1 << g)
        return sign, res

    def product(self, x: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
        """Geometric product of two multivectors given as length-2^n coeff vectors."""
        out = torch.zeros(self.dim, dtype=x.dtype)
        for a in range(self.dim):
            xa = x[a]
            if xa == 0:
                continue
            for b in range(self.dim):
                yb = y[b]
                if yb == 0:
                    continue
                s = self.sign_tab[a, b]
                if s == 0:
                    continue
                res = int(self.idx_tab[a, b].item())
                out[res] = out[res] + s.to(x.dtype) * xa * yb
        return out

    # blade helpers --------------------------------------------------------- #
    def blade(self, gens: tuple[int, ...]) -> torch.Tensor:
        """Unit blade e_{gens} as a coeff vector (gens are 0-based, ascending)."""
        v = torch.zeros(self.dim, dtype=RTYPE)
        mask = 0
        sign = 1
        # reorder via product to get the canonical signed blade
        arr = list(gens)
        for p in range(1, len(arr)):
            q = p
            while q > 0 and arr[q - 1] > arr[q]:
                arr[q - 1], arr[q] = arr[q], arr[q - 1]
                sign = -sign
                q -= 1
        for g in arr:
            mask |= (1 << g)
        v[mask] = float(sign)
        return v

    def vector(self, comps: torch.Tensor) -> torch.Tensor:
        """Grade-1 vector from n real components."""
        v = torch.zeros(self.dim, dtype=RTYPE)
        for i in range(self.n):
            v[1 << i] = comps[i]
        return v

    def scalar(self, s: float) -> torch.Tensor:
        v = torch.zeros(self.dim, dtype=RTYPE)
        v[0] = s
        return v

    def reverse(self, x: torch.Tensor) -> torch.Tensor:
        """Clifford reverse ~x : reverses the order in each blade -> sign
        (-1)^{k(k-1)/2} for grade k."""
        out = x.clone()
        for mask in range(self.dim):
            k = bin(mask).count("1")
            if (k * (k - 1) // 2) % 2 == 1:
                out[mask] = -out[mask]
        return out

    def grade0(self, x: torch.Tensor) -> torch.Tensor:
        out = torch.zeros_like(x)
        out[0] = x[0]
        return out


# --------------------------------------------------------------------------- #
# Rotor: R = exp(-theta/2 B) for a unit bivector B (closed form on a plane)     #
# --------------------------------------------------------------------------- #
def rotor_on_plane(cl: CliffordTorch, i: int, j: int, theta: float) -> torch.Tensor:
    """Rotor exp(-theta/2 e_i e_j) = cos(theta/2) - sin(theta/2) e_i e_j
    (valid because (e_i e_j)^2 = -1 for i!=j Euclidean)."""
    R = cl.scalar(math.cos(theta / 2))
    B = cl.blade((i, j))
    R = R - math.sin(theta / 2) * B
    return R


def rotate_vector(cl: CliffordTorch, R: torch.Tensor, v: torch.Tensor) -> torch.Tensor:
    """Sandwich v -> R v ~R."""
    return cl.product(cl.product(R, v), cl.reverse(R))


def vector_components(cl: CliffordTorch, x: torch.Tensor) -> torch.Tensor:
    return torch.stack([x[1 << i] for i in range(cl.n)])


# --------------------------------------------------------------------------- #
# clifford reference library wrappers                                          #
# --------------------------------------------------------------------------- #
def clifford_layout(n: int):
    layout, blades = Cl(n)
    return layout, blades


def torch_blade_to_clifford(cl: CliffordTorch, layout, vec: torch.Tensor):
    """Map a torch coeff vector (bitmask order) to a clifford MultiVector
    (which uses its own internal blade ordering)."""
    mv = layout.MultiVector()
    # clifford layout has a canonical ordering; build by name
    for mask in range(cl.dim):
        c = float(vec[mask].item())
        if c == 0:
            continue
        gens = [g + 1 for g in range(cl.n) if (mask >> g) & 1]  # 1-based names
        name = "e" + "".join(str(g) for g in gens) if gens else ""
        blade = layout.blades[name]
        mv = mv + c * blade
    return mv


def clifford_mv_to_torch(cl: CliffordTorch, layout, mv) -> torch.Tensor:
    """Map a clifford MultiVector back to a torch coeff vector (bitmask order)."""
    out = torch.zeros(cl.dim, dtype=RTYPE)
    # iterate over clifford's blades and read coefficients
    for name, blade in layout.blades.items():
        coeff = float((mv | blade).value[0]) if name == "" else None
        # robust: use scalar projection (mv * ~blade)_0 / (blade*~blade)_0
        norm0 = float((blade * (~blade)).value[0])
        c = float((mv * (~blade)).value[0]) / norm0 if norm0 != 0 else 0.0
        gens = [int(ch) - 1 for ch in name[1:]] if name.startswith("e") else []
        mask = 0
        for g in gens:
            mask |= (1 << g)
        out[mask] = c
    return out


