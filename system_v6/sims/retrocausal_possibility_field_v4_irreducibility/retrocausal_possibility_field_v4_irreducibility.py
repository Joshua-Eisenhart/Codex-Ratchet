def build_sequence_measure(
    family: list[dict[str, list[str]]],
    seq_fn,
) -> dict[str, Any]:
    n = len(family)
    w = 1.0 / n
    mu: dict[tuple[str, ...], float] = {}
    sequences: list[tuple[str, ...]] = []
    for fc in family:
        seq = seq_fn(fc)
        mu[seq] = mu.get(seq, 0.0) + w
        sequences.append(seq)
    return {"mu": mu, "sequences": sequences, "n": n, "weight_each": w}


# =====================================================================
# (3) Best-fit forward width-N_f Markov kernel under a deterministic embedding e, and
# the generated sequence-measure mu0.K.
# =====================================================================

def best_fit_forward_markov_measure(
    sequences: list[tuple[str, ...]],
    weight: float,
    embedding: dict[str, int],
) -> dict[tuple[str, ...], float]:
    """Given a deterministic embedding e: symbol -> hidden class (image size <= N_f),
    build the BEST-FIT (maximum-likelihood) forward Markov sequence-measure whose step
    t+1 symbol distribution depends on the previous symbol ONLY through e(prev):

        P(x_1..x_L) = pi(x_1) * prod_t  T_t( x_{t+1} | e(x_t) )

    pi  = empirical first-symbol distribution of mu.
    T_t = empirical conditional P(x_{t+1} | class=e(x_t)) at step t, the ML estimate.
    Returns the generated measure over full sequences. This IS the best forward fit for
    this embedding (ML conditionals minimize the forward model's deviation), so taking
    the min over embeddings is the genuine inf over width-<=N_f forward Markov kernels."""
    length = len(sequences[0]) if sequences else 0
    # pi: first-symbol distribution
    pi: dict[str, float] = {}
    for seq in sequences:
        pi[seq[0]] = pi.get(seq[0], 0.0) + weight
    # per-step ML transition conditioned on the embedded class of the previous symbol:
    # counts[t][class][next_symbol]
    counts: list[dict[int, dict[str, float]]] = [dict() for _ in range(length - 1)]
    for seq in sequences:
        for t in range(length - 1):
            c = embedding[seq[t]]
            counts[t].setdefault(c, {})
            counts[t][c][seq[t + 1]] = counts[t][c].get(seq[t + 1], 0.0) + weight
    # conditional distributions
    trans: list[dict[int, dict[str, float]]] = []
    for t in range(length - 1):
        layer: dict[int, dict[str, float]] = {}
        for c, nexts in counts[t].items():
            z = sum(nexts.values())
            layer[c] = {s: m / z for s, m in nexts.items()} if z > 0 else {}
        trans.append(layer)
    # generate the full forward measure
    generated: dict[tuple[str, ...], float] = {}

    def expand(prefix: tuple[str, ...], prob: float):
        t = len(prefix) - 1
        if len(prefix) == length:
            generated[prefix] = generated.get(prefix, 0.0) + prob
            return
        c = embedding[prefix[-1]]
        layer = trans[t].get(c, {})
        for nxt, p in layer.items():
            expand(prefix + (nxt,), prob * p)

    for x1, p1 in pi.items():
        expand((x1,), p1)
    return generated


def total_variation(mu_a: dict[Any, float], mu_b: dict[Any, float]) -> float:
    keys = set(mu_a) | set(mu_b)
    return 0.5 * sum(abs(mu_a.get(k, 0.0) - mu_b.get(k, 0.0)) for k in keys)


# =====================================================================
# (4) Exhaustive search over deterministic embeddings of size <= N_f -> tv_infimum.
# =====================================================================

def _deterministic_embeddings(symbols: list[str], n_f: int):
    """Yield every deterministic embedding symbols -> {0..N_f-1} (each symbol assigned
    to one of <= N_f hidden classes). Exhaustive over deterministic <= N_f-class maps."""
    for assignment in itertools.product(range(n_f), repeat=len(symbols)):
        yield {sym: assignment[i] for i, sym in enumerate(symbols)}


def tv_infimum_over_forward_markov(
    sequences: list[tuple[str, ...]],
    mu: dict[tuple[str, ...], float],
    weight: float,
    n_f: int,
) -> dict[str, Any]:
    """Exact inf over deterministic width-<=N_f forward Markov kernels of TV(mu, mu0.K),
    by exhaustive search over deterministic embeddings of the symbol set into <= N_f
    classes. Returns the infimum and whether mu factors as a width-N_f forward chain."""
    symbols = sorted({s for seq in sequences for s in seq})
    best_tv = None
    best_embedding = None
    n_embeddings = 0
    for emb in _deterministic_embeddings(symbols, n_f):
        n_embeddings += 1
        gen = best_fit_forward_markov_measure(sequences, weight, emb)
        tv = total_variation(mu, gen)
        if best_tv is None or tv < best_tv:
            best_tv = tv
            best_embedding = dict(emb)
    return {
        "n_symbols": len(symbols),
        "N_f": n_f,
        "n_embeddings_searched": n_embeddings,
        "tv_infimum": best_tv if best_tv is not None else 1.0,
        "best_embedding": best_embedding,
        "factors_as_width_Nf_forward_markov": (best_tv is not None and best_tv <= 1e-12),
    }


# =====================================================================
# (5) The discriminator on a carrier-family + output-sequence function.
# =====================================================================

def run_discriminator(family, seq_fn, n_f: int, *, label: str) -> dict[str, Any]:
    sm = build_sequence_measure(family, seq_fn)
    tv = tv_infimum_over_forward_markov(sm["sequences"], sm["mu"], sm["weight_each"], n_f)
    irreducible = tv["tv_infimum"] > TV_THRESHOLD
    return {
        "label": label,
        "family_size": sm["n"],
        "mu": {"|".join(k): v for k, v in sm["mu"].items()},
        "n_distinct_output_sequences": len(sm["mu"]),
        "output_sequences": [list(s) for s in sm["sequences"]],
        "N_f": n_f,
        "tv_search": tv,
        "tv_infimum": tv["tv_infimum"],
        "threshold": TV_THRESHOLD,
        "irreducible_to_forward_hidden_state": irreducible,
    }


# =====================================================================
# THE NEGATIVE CONTROL: a selection whose output sequence IS a width-N_f forward Markov
# chain by construction (tv -> 0). Each shell emits its own lowest-id branch
# independently of the others -> the sequence factorizes with NO cross-shell coupling,
# so a width-1 (constant-class) forward chain reproduces it exactly. Proves the test
# can return 'reducible' -- it is not rigged to always say 'irreducible'.
# =====================================================================

def reducible_output_sequence(fc: dict[str, list[str]]) -> tuple[str, ...]:
    """Forward-reducible selection: each shell independently picks its own lowest-id
    branch. No cross-shell joint view; the sequence-measure factorizes as independent
    per-position choices, the simplest width-N_f forward Markov chain."""
    return tuple(sorted(fc[sid])[0] for sid in SHELL_ORDER)


# =====================================================================
# FAMILY-SENSITIVITY SWEEP (anti-cherry-pick). The verdict can sit near the threshold
