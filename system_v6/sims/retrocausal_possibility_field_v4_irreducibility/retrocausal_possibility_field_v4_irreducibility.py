def global_output_sequence(fc: dict[str, list[str]]) -> tuple[str, ...]:
    relation = rpf_v3.co_admissibility_relation(fc)
    retro = rpf_v3.retrocausal_global_compressor(fc, relation, rpf_v3.SHELLS)
