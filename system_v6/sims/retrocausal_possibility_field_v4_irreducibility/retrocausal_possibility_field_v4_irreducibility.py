POOL_OUTER = ["b1", "b6", "b7"]   # Sigma_3 draws from here
POOL_MID = ["b0", "b4", "b5"]     # Sigma_2 draws from here
POOL_INNER = ["b2", "b3", "b8"]   # Sigma_1 draws from here


def perturbation_family(k_outer: int = 2, k_mid: int = 2, k_inner: int = 2) -> list[dict[str, list[str]]]:
    """Independent-draw family: each shell carries a k-subset of its OWN disjoint pool,
    chosen independently of the other shells. Default k=2 per shell over 3-element pools
    gives 3*3*3 = 27 instances. mu spans multiple distinct output sequences and the
    family imposes no cross-shell constraint of its own."""
    family: list[dict[str, list[str]]] = []
    for o in itertools.combinations(POOL_OUTER, k_outer):
        for mi in itertools.combinations(POOL_MID, k_mid):
            for inn in itertools.combinations(POOL_INNER, k_inner):
                fc = {"Sigma_3": list(o), "Sigma_2": list(mi), "Sigma_1": list(inn)}
                if _valid_v3_carrier(fc):
                    family.append(fc)
    return family


