# DISJOINT per-shell pools: the outer/mid/inner shells draw their content from three
# DISJOINT branch pools. This is the honest family design: each shell's content is drawn
# INDEPENDENTLY, so the FAMILY itself injects NO cross-shell constraint (no "leftover"
# permutation artifact). Any irreducible cross-shell coupling in the output sequence-
# measure can therefore come ONLY from the selection rule (the global compressor), not
# from the family construction. (An earlier permute-the-blocks family was REJECTED in
